def bucket_sort(arr):
    buckets = [[] for _ in range(10)]

    for num in arr:
        index = int(num * 10)
        buckets[index].append(num)

    for i in range(10):
        buckets[i].sort()

    result = []
    for b in buckets:
        result.extend(b)

    return result

print(bucket_sort([0.12, 0.87, 0.45, 0.33]))



# طرز کار Bucket Sort
# ایده‌ی اصلی این الگوریتم این است که داده‌ها را به چندین سطل (Bucket) مجزا تقسیم می‌کند و سپس هر سطل را به‌طور جداگانه مرتب می‌کند. این روش وقتی عالی عمل می‌کند که داده‌ها در یک بازه‌ی مشخص، به‌طور یکنواخت (Uniformly) توزیع شده باشند.
#
# الگوریتم در چهار مرحله‌ی اصلی انجام می‌شود:
#
# مرحله‌ی ۱: ایجاد سطل‌ها (Create Buckets)
# یک آرایه‌ی خالی از سطل‌ها (معمولاً به تعداد n یا کمتر) ایجاد می‌کنیم. هر سطل می‌تواند یک لیست (آرایه پویا) باشد.
#
# مرحله‌ی ۲: توزیع عناصر (Distribution)
# هر عنصر از آرایه‌ی اصلی را بر اساس یک تابع نگاشت (Mapping Function) به یکی از سطل‌ها اختصاص می‌دهیم. این تابع باید طوری باشد که اگر عددی بزرگتر است، به سطل بالاتری برود. مثلاً برای اعداد بین ۰ و ۱، تابع ضرب در تعداد سطل‌ها می‌تواند استفاده شود.
#
# مرحله‌ی ۳: مرتب‌سازی سطل‌ها (Sort Buckets)
# حالا هر سطلی که چند عنصر دارد را به‌طور جداگانه مرتب می‌کنیم. معمولاً از مرتب‌سازی درجی (Insertion Sort) استفاده می‌شود، چون هر سطل کوچک است و Insertion Sort روی داده‌های کوچک بسیار سریع عمل می‌کند. (می‌توان از هر الگوریتم مرتب‌سازی دیگری هم استفاده کرد).
#
# مرحله‌ی ۴: ادغام سطل‌ها (Concatenation)
# همه‌ی سطل‌ها را به ترتیب (از سطل اول تا آخر) به هم می‌چسبانیم تا آرایه‌ی نهایی مرتب‌شده به دست آید.


# مرتبه‌ی زمانی (پیچیدگی):
#
# حالت متوسط و بهترین: O(n + k) — اگر داده‌ها به‌طور یکنواخت بین سطل‌ها پخش شوند، هر سطل تقریباً n/k عنصر دارد و مرتب‌سازی هر سطل با Insertion Sort از مرتبه‌ی O(1) خواهد بود. در این حالت، کل الگوریتم خطی است.
#
# بدترین حالت: O(n²) — زمانی رخ می‌دهد که همه‌ی عناصر در یک سطل بریزند (داده‌ها یکنواخت نباشند). در این حالت، همه‌چیز به مرتب‌سازی همان یک سطل بزرگ با O(n²) تبدیل می‌شود.
#
# مرتبه‌ی حافظه (فضای اضافی): O(n + k) — به حافظه‌ی اضافی برای نگهداری سطل‌ها نیاز دارد.
#
# آیا پایدار (Stable) است؟ بستگی به الگوریتمی دارد که برای مرتب‌سازی داخل سطل‌ها استفاده می‌کنیم. اگر داخل سطل‌ها را با یک الگوریتم پایدار (مثل Insertion Sort) مرتب کنیم، کل Bucket Sort پایدار خواهد بود. اگر با الگوریتم ناپایدار (مثل Quick Sort) مرتب کنیم، ناپایدار می‌شود.
#
# چه زمانی عالی عمل می‌کند؟ زمانی که داده‌ها به‌طور یکنواخت در یک بازه توزیع شده‌اند. مثلاً نمرات دانشجویان، سن افراد، یا اعداد اعشاری تصادفی بین ۰ و ۱
#
# محدودیت‌های اصلی:
#
# نیاز به دانش قبلی از بازه‌ی داده‌ها برای طراحی تابع نگاشت مناسب دارد.
#
# اگر توزیع داده‌ها یکنواخت نباشد، کارایی به شدت کاهش می‌یابد و به بدترین حالت O(n²) می‌رسد.
#
