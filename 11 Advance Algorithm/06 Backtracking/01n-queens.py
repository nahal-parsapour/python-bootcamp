# مسئله این است که تعداد N وزیر را در صفحه‌ی شطرنجی به ابعاد N × N قرار دهیم به‌طوری که هیچ دو وزیری همدیگر را تهدید نکنند.
# طبق قوانین شطرنج، یک وزیر می‌تواند به صورت افقی، عمودی، و هر دو قطر (اصلی و فرعی) حرکت کند. بنابراین، شرط حل این است که:
#
# هیچ دو وزیری در یک سطر (Row) نباشند.
#
# هیچ دو وزیری در یک ستون (Column) نباشند.
#
# هیچ دو وزیری در یک قطر (Diagonal) نباشند.
#
# طرز کار الگوریتم (روش بازگشت به عقب - Backtracking)
# این الگوریتم از روش «بازگشت به عقب» (Backtracking) استفاده می‌کند که یک نوع جستجوی عمق‌اول (DFS) هوشمند است. ایده این است که وزیرها را سطر به سطر (از بالا به پایین) قرار دهیم و هر بار که به بن‌بست رسیدیم، یک قدم به عقب برگردیم و جای وزیر قبلی را عوض کنیم.
#
# مراحل گام‌به‌گام (بهینه‌شده با آرایه‌های کمکی):
#
# از سطر اول (ردیف ۰) شروع کنید.
#
# برای سطر جاری، ستون‌ها را یکی‌یکی (از ۰ تا N-1) امتحان کنید.
#
# قبل از قرار دادن وزیر در ستون موردنظر، بررسی امنیت (Safe Check) را انجام دهید:
#
# آیا ستون موردنظر قبلاً توسط وزیر دیگری اشغال شده است؟
#
# آیا قطر اصلی (از بالا‑چپ به پایین‑راست) اشغال شده است؟ (فرمول: تفاوت سطر و ستون یکسان است یا در روش آرایه‌ای: row - col + N - 1 ثابت است)
#
# آیا قطر فرعی (از بالا‑راست به پایین‑چپ) اشغال شده است؟ (فرمول: مجموع سطر و ستون یکسان است)
#
# اگر همه‌ی بررسی‌ها امن بود:
#
# وزیر را در آن خانه قرار دهید (ستون را علامت‌گذاری کنید، و قطرهای متناظر را اشغال کنید).
#
# به‌صورت بازگشتی (Recursive) به سطر بعدی (row + 1) بروید.
#
# اگر در سطر بعدی به بن‌بست خوردیم (هیچ ستونی امن نبود)، تابع بازگشتی برمی‌گردد (Backtrack) و وزیر سطر قبلی را از خانه‌اش خارج می‌کند (علامت‌ها را پاک می‌کند) تا ستون بعدی را امتحان کند.
#
# وقتی موفق شدیم وزیرها را تا سطر آخر (row == N) قرار دهیم، یعنی یک جواب کامل پیدا کردیم. آن را ذخیره کرده و به جستجوی جواب‌های دیگر ادامه می‌دهیم.




# مرتبه‌ی زمانی (پیچیدگی): در حالت کلی، O(N!) است، چون در بدترین حالت، الگوریتم باید تمام جایگشت‌های ممکن ستون‌ها را بررسی کند. (البته با برش‌های هوشمند (Pruning) در Backtracking، در عمل بسیار کمتر از N! است).
#
# مرتبه‌ی حافظه (فضای اضافی):
#
# عمق بازگشت: O(N) (برای پشته‌ی فراخوانی).
#
# آرایه‌های کمکی: O(N) برای cols و O(N) برای هر کدام از قطرها (مجموعاً O(N)).
#
# اگر صفحه را ذخیره کنیم، O(N²) می‌شود، اما معمولاً فقط آرایه‌های کمکی را نگه می‌داریم.
#
# خروجی الگوریتم: معمولاً یک لیست از N عدد برمی‌گرداند که هر عدد نشان‌دهنده‌ی ستون وزیر در هر سطر است.
#
# دلیل استفاده از Backtracking (بازگشت به عقب): این مسئله یک مسئله‌ی محدودیت‌دار (Constraint Satisfaction Problem) است که در آن، انتخاب‌های قبلی مستقیماً روی انتخاب‌های بعدی تأثیر می‌گذارند. جستجوی کامل (Brute Force) تعداد حالت‌های N^N را بررسی می‌کند، اما Backtracking با تشخیص زودهنگام بن‌بست، شاخه‌های مرده را هرس کرده و سرعت را به شدت افزایش می‌دهد.
#
# کاربردهای واقعی: مسائل زمان‌بندی (Scheduling)، تخصیص فرکانس در شبکه‌های بی‌سیم، حل جدول سودوکو، و به طور کلی هر مسئله‌ای که نیاز به چیدمان اشیاء با محدودیت‌های مشخص دارد.