def heapify(arr, n, i):
    largest = i
    l = 2*i + 1
    r = 2*i + 2

    if l < n and arr[1] > arr[largest]:
        largest = l
    if r < n and arr[r] > arr[largest]:
        largest = r

    if largest != i:
        arr[i], arr[largest] = arr[largest], arr[i]
        heapify(arr, n, largest)

def heap_sort(arr):
    n = len(arr)

    for i in range(n//2 - 1, -1, -1):
        heapify(arr, n, i)

    for i in range(n-1, 0, -1):
        arr[i], arr[0] = arr[0], arr[i]
        heapify(arr, i, 0)

    return arr

print(heap_sort([5, 3, 8, 0, 4, 2]))




# ایده‌ی اصلی این الگوریتم، استفاده از ساختمان داده‌ی هِپ (Heap) است؛ به‌طور خاص هِپ بیشینه (Max-Heap). در یک هپ بیشینه، بزرگترین عنصر همیشه در ریشه (خانه‌ی اول آرایه) قرار دارد.
#
# الگوریتم در دو مرحله‌ی اصلی انجام می‌شود:
#
# مرحله‌ی ۱: ساخت هپ بیشینه (Build Max-Heap)
# آرایه‌ی نامرتب را به یک هپ بیشینه تبدیل می‌کنیم. یعنی طوری آرایه را بازچینی می‌کنیم که قانون هپ برقرار شود: مقدار هر پدر، از فرزندانش بزرگ‌تر یا مساوی باشد.
#
# مرحله‌ی ۲: استخراج و مرتب‌سازی (Extract & Sort)
# تا وقتی که عنصری در هپ باقی مانده است:
#
# بزرگترین عنصر (ریشه یا همان خانه‌ی اول) را با آخرین عنصر هپ جابه‌جا می‌کنیم.
#
# آن عنصر آخر را از هپ حذف می‌کنیم (در واقع دیگر به آن دست نمی‌زنیم؛ در انتهای آرایه قرار می‌گیرد و جای نهایی خود را پیدا می‌کند).
#
# چون با جابه‌جایی، قانون هپ به هم خورده است، تابع «بازیابی پایین‌رونده» (Heapify) را روی ریشه اجرا می‌کنیم تا دوباره هپ بیشینه را برقرار کنیم.




# مرتبه‌ی زمانی (پیچیدگی): در بهترین، متوسط و بدترین حالت، همگی O(n log n) هستند. (ساخت هپ اولیه O(n) زمان می‌برد و خود مرتب‌سازی O(n log n) زمان می‌برد، پس مجموعاً O(n log n) می‌شود).
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — کاملاً درجا (In-place) است و بر خلاف Merge Sort، حافظه‌ی اضافی به اندازه‌ی آرایه مصرف نمی‌کند (فقط چند متغیر موقت برای جابه‌جایی).
#
# آیا پایدار (Stable) است؟ خیر. چون عناصر را با جابه‌جایی‌های گسترده (Swap) بین ریشه و انتهای آرایه ردوبدل می‌کند، ترتیب نسبی عناصر مساوی به هم می‌ریزد.
#
# مزیت اصلی: عملکرد تضمینی و ثابت (O(n log n) دارد و برخلاف Quick Sort، دچار بدترین حالت O(n²) نمی‌شود. برای سیستم‌های بیدرنگ (Real-time) که تضمین زمان اجرا مهم است، گزینه‌ی مناسبی است.
#
# معایب اصلی: در عمل، معمولاً از Quick Sort کندتر است، چون دسترسی به حافظه به صورت پرشی (غیرهمجوار) انجام می‌شود و از حافظه‌ی کش (Cache) پردازنده به خوبی استفاده نمی‌کند. همچنین پیاده‌سازی آن نسبت به بقیه پیچیده‌تر است.
