activities = [(1,4),(3,5),(0,6),(5,7),(3,9),(5,9),(6,10),(8,11)]

# 1) sort by finish time
activities_sorted = sorted(activities, key=lambda x: x[1])

# 2) انتخاب فعالیت‌های غیرهمپوشان
selected = []
last_finish = -1

for s, f in activities_sorted:
    if s >= last_finish:
        selected.append((s,f))
        last_finish = f

print("Selected:", selected)




