# مشکل اصلی فیبوناچی به روش تقسیم و حل (بازگشتی ساده)
# قبل از توضیح DP، اجازه دهید مشکل روش ساده را ببینیم. رابطه‌ی فیبوناچی به این صورت است:
# F(n) = F(n-1) + F(n-2) با شرایط پایه F(0) = 0 و F(1) = 1.
#
# اگر این را به‌صورت بازگشتی ساده (Naive Recursion) بنویسیم، برای محاسبه‌ی F(5)، درخت زیر ساخته می‌شود:
#
# F(5) یک بار محاسبه می‌شود.
#
# F(4) یک بار، F(3) دو بار، F(2) سه بار، و F(1) پنج بار محاسبه می‌شود!
#
# این یعنی محاسبات تکراری (Overlapping Subproblems) بیشمار. به همین دلیل، زمان اجرای روش ساده O(2ⁿ) (نمایی) است که برای اعداد بزرگ مثل ۵۰ کاملاً غیرقابل اجراست.
#
# راه‌حل با برنامه‌ریزی پویا (Dynamic Programming)
# ایده‌ی اصلی DP در اینجا این است: «هر عدد فیبوناچی را فقط یک بار محاسبه کن و نتیجه را در جایی ذخیره کن تا دفعه‌ی بعد که به آن نیاز شد، دوباره محاسبه‌اش نکنی.»
#
# این کار با سه روش متفاوت انجام می‌شود که از ساده به پیشرفته توضیح می‌دهم:
#
# روش اول: رویکرد بالا به پایین (Top-Down) یا «مموایزیشن» (Memoization)
# (همان بازگشت، اما با کش)
#
# یک آرایه‌ی کمکی به نام memo با اندازه‌ی n+1 ایجاد می‌کنیم و همه‌ی خانه‌های آن را با مقدار -1 (یا ۰) پر می‌کنیم تا نشان دهیم هنوز محاسبه نشده‌اند.
#
# تابع بازگشتی را می‌نویسیم، اما قبل از هر محاسبه، ابتدا به memo[n] نگاه می‌کنیم:
#
# اگر مقدار آن -1 نبود، یعنی قبلاً محاسبه شده، همان مقدار را بلافاصله برمی‌گردانیم (بدون هیچ محاسبه‌ی جدیدی).
#
# اگر -1 بود، آن را محاسبه کرده، در memo[n] ذخیره می‌کنیم و سپس برمی‌گردانیم.
#
# مرتبه‌ی زمانی: O(n) (چون هر عدد فقط یک بار محاسبه می‌شود).
#
# مرتبه‌ی حافظه: O(n) (برای آرایه‌ی کش) + O(n) (برای پشته‌ی بازگشت) = O(n).
#
# روش دوم: رویکرد پایین به بالا (Bottom-Up) یا «تبلیشن» (Tabulation)
# (حذف بازگشت و استفاده از حلقه)
#
# یک آرایه‌ی کمکی به نام dp با اندازه‌ی n+1 ایجاد می‌کنیم.
#
# شرایط پایه را مستقیماً در آن می‌ریزیم: dp[0] = 0 و dp[1] = 1.
#
# سپس از اندیس ۲ شروع می‌کنیم و تا n جلو می‌رویم:
#
# در هر مرحله، dp[i] = dp[i-1] + dp[i-2] را محاسبه می‌کنیم.
#
# در نهایت، پاسخ در dp[n] قرار دارد.
#
# مرتبه‌ی زمانی: O(n) (یک حلقه‌ی ساده).
#
# مرتبه‌ی حافظه: O(n) (برای آرایه‌ی dp).
#
# روش سوم: بهینه‌سازی فضای حافظه (فضای O(1))
# (بهترین و رایج‌ترین روش برای فیبوناچی)
#
# اگر دقت کنید، برای محاسبه‌ی F(n)، فقط به دو عدد قبلی یعنی F(n-1) و F(n-2) نیاز داریم. نیازی به نگهداری کل آرایه نیست!
#
# دو متغیر prev2 = 0 (مشابه F(0)) و prev1 = 1 (مشابه F(1)) در نظر می‌گیریم.
#
# اگر n == 0، همان 0 را برمی‌گردانیم. اگر n == 1، همان 1 را برمی‌گردانیم.
#
# یک حلقه از ۲ تا n می‌زنیم:
#
# current = prev1 + prev2
#
# سپس prev2 = prev1 (عدد قبلی‌ترین، می‌شود عدد قبلی)
#
# و prev1 = current (عدد قبلی، می‌شود عدد جاری)
#
# در پایان حلقه، prev1 همان F(n) خواهد بود.
#
# مثال برای n = 5:
#
# شروع: prev2 = 0 (F0)، prev1 = 1 (F1)
#
# i=2: current = 0+1=1 → prev2=1, prev1=1 (F2=1)
#
# i=3: current = 1+1=2 → prev2=1, prev1=2 (F3=2)
#
# i=4: current = 1+2=3 → prev2=2, prev1=3 (F4=3)
#
# i=5: current = 2+3=5 → prev2=3, prev1=5 (F5=5)
#
# خروجی: 5
#
# مرتبه‌ی زمانی: O(n)
#
# مرتبه‌ی حافظه: O(1) (فقط دو متغیر!)




# مرتبه‌ی زمانی: O(n) در هر سه روش (در مقابل O(2ⁿ) در روش بازگشتی ساده).
#
# مرتبه‌ی حافظه: بسته به روش، بین O(1) (بهینه) تا O(n) (تبلیشن و مموایزیشن).
#
# دلیل استفاده از DP در اینجا (اصل موضوع): این مسئله دو ویژگی کلیدی DP را دارد:
#
# زیرمسئله‌های همپوشان (Overlapping Subproblems): F(3) هم در محاسبه‌ی F(4) و هم در F(5) تکرار می‌شود.
# ساختار بهینه (Optimal Substructure): جواب نهایی F(n) مستقیماً از ترکیب جواب‌های زیرمسئله‌های کوچک‌تر (F(n-1) و F(n-2)) به دست می‌آید.
# کاربرد اصلی آموزشی: این مثال، «سلام دنیا» (Hello World) دنیای برنامه‌ریزی پویا محسوب می‌شود. هر دانشجوی علوم کامپیوتر اولین برخوردش با DP دقیقاً با همین مسئله است تا تفاوت بین بازگشت ساده و DP را به خوبی درک کند.
#
# نکته‌ی مهم: روش سوم (فضای O(1)) در عمل بهترین است، اما در مسائل پیچیده‌تر که وابستگی به بیش از دو حالت قبلی وجود دارد، ناگزیر به استفاده از آرایه‌ی dp (روش دوم) خواهید بود.
