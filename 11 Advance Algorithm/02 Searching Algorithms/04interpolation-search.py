arr  = list(range(0, 1000, 10))
target = 430

steps = 0
low, high = 0, len(arr)-1

while low <= high and target >= arr[low] and target <= arr[high]:
    pos = low + ((target - arr[low]) * (high - low)) // arr[high] - arr[low]
    steps += 1

    print(f"pos={pos}, arr[pos]={arr[pos]}")

    if arr[pos] == target:
        break
    elif arr[pos] < target:
        low = pos + 1
    else:
        high = pos - 1

print("Steps:", steps)



