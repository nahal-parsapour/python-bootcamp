# External Sorting Algorithms
def external_merge_sort(chunks):
    sorted_chunks = [sorted(chunk) for chunk in chunks]
    print("Initial sorted chunks:", sorted_chunks)

    result = []
    indices = [0] * len(sorted_chunks)

    step = 0
    while True:
        step += 1
        min_val = None
        min_idx = -1

        for i, chunk in enumerate(sorted_chunks):
            if indices[i] < len(chunk):
                val = chunk[indices[i]]
                if min_val is None or val < min_val:
                    min_val = val
                    min_idx = i

        if min_idx == -1:
            break

        print(f"Step {step}: take {min_val} from chunk {min_idx}")
        result.append(min_val)
        indices[min_idx] += 1

    print("Final merged result:", result)
    return result

chunks = [
    [9, 1, 5],
    [3, 8, 2],
    [7, 4, 6]
]
external_merge_sort(chunks)







# Merge Sort معمولی فرض می‌کند که کل آرایه در حافظه‌ی اصلی (RAM) جا می‌شود. اما External Merge Sort برای زمانی طراحی شده است که حجم داده‌ها آنقدر زیاد است که در حافظه‌ی اصلی (RAM) نمی‌گنجد و باید از حافظه‌ی ثانویه (مانند هارد دیسک یا SSD) استفاده کند. بنابراین، هدف اصلی این الگوریتم، کمینه‌سازی تعداد دفعات خواندن و نوشتن روی دیسک (I/O) است، چون عملیات دیسک بسیار کندتر از عملیات حافظه است.
#
# طرز کار External Merge Sort
# این الگوریتم از استراتژی «تقسیم، مرتب‌سازی، و ادغام» پیروی می‌کند، اما در دو فاز اصلی در سطح دیسک اجرا می‌شود:
#
# فاز اول: مرتب‌سازی درونی و ایجاد اجراها (Run Creation / Sorting Phase)
# در این فاز، داده‌ی عظیم را به تکه‌های کوچکی تقسیم می‌کنیم که هر کدام در RAM جا می‌شوند.
#
# داده‌ی اصلی را از دیسک خوانده و به بلوک‌های کوچک (معمولاً به اندازه‌ی حافظه‌ی موجود) تقسیم می‌کنیم.
#
# هر بلوک را یک‌باره به RAM می‌آوریم و با یک الگوریتم مرتب‌سازی سریع درون‌حافظه‌ای (مثل Quick Sort یا IntroSort) آن را مرتب می‌کنیم.
#
# هر بلوک مرتب‌شده را به عنوان یک «اجرا» (Run) روی دیسک ذخیره می‌کنیم.
# در پایان این فاز، به جای یک فایل عظیم نامرتب، تعدادی فایل کوچک‌تر و کاملاً مرتب (اجراها) روی دیسک داریم.
#
# فاز دوم: ادغام چندراهه (Multi-way Merge Phase)
# حالا نوبت چسباندن اجراها به هم است تا به یک فایل مرتب‌شده‌ی واحد برسیم. برای کاهش تعداد دفعات اسکن دیسک، از ادغام چندراهه (Multi-way Merge) استفاده می‌کنیم.
#
# تعداد اجراهایی که می‌توانیم همزمان با هم ادغام کنیم را درجه‌ی ادغام (Degree of Merge) یا B می‌نامند. این عدد به اندازه‌ی بافرهای موجود در RAM بستگی دارد.
#
# از بین B اجرای اول، هر بار کوچکترین عنصر را انتخاب کرده و در خروجی می‌نویسیم. (برای این کار از یک هیپ (Heap) یا صف اولویت (Priority Queue) در RAM استفاده می‌کنیم تا همیشه کوچکترین عنصر بین سرِ همه‌ی اجراها را با سرعت O(log B) پیدا کنیم).
#
# وقتی یک اجرا کاملاً مصرف شد، اجرای بعدی را از دیسک به جای آن می‌آوریم.
#
# اگر بعد از یک مرحله‌ی ادغام، هنوز تعداد اجراها بیشتر از ۱ باشد، این کار را تکرار می‌کنیم (ادغام اجراها با هم تا به یک اجرای نهایی برسیم).

# برای کاهش بیشتر I/O، در حین ادغام، از بافر (Buffer) استفاده می‌کنیم. به جای اینکه هر بار یک عدد از دیسک بخوانیم، یک بلوک کامل از هر اجرا را یک‌جا در RAM می‌خوانیم (بافر ورودی). وقتی آن بافر تمام شد، بلوک بعدی را از دیسک می‌خوانیم. همچنین یک بافر خروجی داریم که وقتی پر شد، یک‌جا روی دیسک می‌نویسیم.




# معیار اصلی کارایی: نه تعداد مقایسه‌ها، بلکه تعداد دسترسی‌های I/O به دیسک است. الگوریتم سعی می‌کند تا حد ممکن تعداد پاس‌های ادغام را کاهش دهد (با افزایش درجه‌ی ادغام).
#
# مرتبه‌ی زمانی (از نظر دیسک): اگر n تعداد رکوردها و B درجه‌ی ادغام باشد، تعداد پاس‌های ادغام برابر log_B(n) است. این یعنی مرتبه‌ی اجرا O(n log_B n) در تعداد I/Oها است.
#
# مرتبه‌ی حافظه (RAM): به اندازه‌ی (تعداد بافرهای ورودی × اندازه‌ی هر بافر) + (۱ بافر خروجی) نیاز دارد که کل آن باید از حافظه‌ی موجود کمتر باشد.
#
# آیا پایدار (Stable) است؟ بله. اگر در مرحله‌ی ادغام، هنگام برابری عناصر، اول عنصر اجرای قبلی را انتخاب کنیم، ترتیب نسبی عناصر مساوی حفظ می‌شود.
#
# کاربرد اصلی: پایگاه‌های داده (Database) و سیستم‌های فایل هنگام مرتب‌سازی جداول بزرگ که از حافظه‌ی کش فراتر می‌روند. همچنین در مرتب‌سازی فایل‌های لاگ (گزارش‌های سرور) که حجمشان چندین گیگابایت است، استفاده می‌شود.
#
# مزیت اصلی: تنها راه ممکن برای مرتب‌سازی داده‌های «بزرگ‌تر از حافظه» است و با افزایش درجه‌ی ادغام (با صرف حافظه‌ی بیشتر برای بافرها)، می‌توان آن را به‌شدت بهینه کرد.
#
# معایب اصلی: وابستگی شدید به سرعت دیسک (در دیسک‌های مکانیکی قدیمی بسیار کند بود، اما در SSDها بهبود یافته است). همچنین پیاده‌سازی آن نسبت به الگوریتم‌های درون‌حافظه‌ای بسیار پیچیده‌تر است و مدیریت حافظه (آلوكیشن بافرها) نیازمند دقت بالایی است.