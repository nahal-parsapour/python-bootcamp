# مسئله این است که یک الگو (Pattern) را درون یک متن (Text) بزرگ جستجو کنیم و موقعیت همه‌ی وقوع‌های آن را پیدا کنیم.
#
# مشکل روش ساده (Naive): در روش ساده، اگر بعد از چند تطابق موفق، در کاراکتر بعدی به عدم‌تطابق (Mismatch) برسیم، الگو را یک خانه به جلو می‌بریم و دوباره از صفر شروع می‌کنیم. این یعنی اطلاعاتی که از تطابق‌های قبلی به دست آورده‌ایم را کاملاً دور می‌ریزیم (مثلاً اگر "ABCAB" را تطابق داده باشیم و در کاراکتر بعدی شکست بخوریم، نمی‌دانیم که "AB" در انتهای آن تکرار شده است).
#
# راه‌حل KMP: به جای عقب‌گرد در متن، از یک آرایه‌ی کمکی استفاده می‌کند که به ما می‌گوید وقتی در یک کاراکتر خاص از الگو به عدم‌تطابق رسیدیم، چند کاراکتر از ابتدای الگو را می‌توانیم نادیده بگیریم و دوباره چک نکنیم. به این ترتیب، هر کاراکتر متن فقط یک بار بررسی می‌شود.
#
# قلب الگوریتم: آرایه‌ی LPS (یا تابع پیشوندی - Prefix Function)
# LPS مخفف Longest Proper Prefix which is also Suffix است.
# برای هر اندیس i در الگو، LPS[i] برابر است با طول بلندترین پیشوند (Prefix) واقعی (که نمی‌تواند خود کل رشته باشد) که همان پسوند (Suffix) رشته‌ی pattern[0..i] نیز باشد.
#
# مثال برای الگوی ABABAC:
#
# i=0 (رشته A): نه پیشوند و نه پسوندی وجود دارد → 0
#
# i=1 (رشته AB): پیشوندهای A، پسوندهای B → هیچ‌کدام برابر نیستند → 0
#
# i=2 (رشته ABA): پیشوند A و پسوند A برابرند. طول = ۱ → 1
#
# i=3 (رشته ABAB): پیشوند AB و پسوند AB برابرند. طول = ۲ → 2
#
# i=4 (رشته ABABA): پیشوند ABA و پسوند ABA برابرند. طول = ۳ → 3
#
# i=5 (رشته ABABAC): پسوند C با هیچ پیشوندی برابر نیست → 0
#
# آرایه‌ی LPS: [0, 0, 1, 2, 3, 0]
#
# طرز کار گام‌به‌گام
# الگوریتم دو فاز اصلی دارد: پردازش الگو (ساخت LPS) و جستجو در متن.
#
# فاز اول: ساخت آرایه‌ی LPS (پردازش الگو)
# این کار با دو اشاره‌گر انجام می‌شود:
#
# i = 1 (از دومین کاراکتر شروع کن)، len = 0 (طول بلندترین پیشوند-پسوند فعلی).
#
# تا وقتی به انتهای الگو نرسیده‌ایم:
#
# اگر pattern[i] == pattern[len] → len++، LPS[i] = len، و i++.
#
# اگر برابر نبودند و len != 0 → len = LPS[len-1] (به عقب برمی‌گردیم تا یک پیشوند کوچک‌تر را امتحان کنیم).
#
# اگر برابر نبودند و len == 0 → LPS[i] = 0 و i++.
#
# فاز دوم: جستجو در متن
# دو اشاره‌گر داریم:
#
# i برای پیمایش متن (از ۰ شروع).
#
# j برای پیمایش الگو (از ۰ شروع).
#
# تا وقتی به انتهای متن نرسیده‌ایم:
#
# اگر text[i] == pattern[j] → i++ و j++.
#
# اگر j == طول الگو → یک وقوع پیدا شد. موقعیت را ذخیره کن (i - j). سپس j = LPS[j-1] (تا جستجو برای وقوع‌های بعدی ادامه یابد).
#
# اگر عدم‌تطابق داشتیم (text[i] != pattern[j]):
#
# اگر j != 0 → j = LPS[j-1] (بدون تغییر i، یعنی متن را عقب نمی‌زنیم).
#
# اگر j == 0 → i++ (به کاراکتر بعدی متن برو).




# مرتبه‌ی زمانی (پیچیدگی):
#
# ساخت LPS: O(m) که m طول الگوست.
#
# جستجو در متن: O(n) که n طول متن است.
#
# مجموعاً: O(n + m) (که نسبت به روش ساده‌ی O(n×m) یک پیشرفت عظیم است).
#
# مرتبه‌ی حافظه (فضای اضافی): O(m) (برای نگهداری آرایه‌ی LPS).
#
# مزیت اصلی (چرا خاص است؟): هیچ‌گاه متن را به عقب برنمی‌گرداند (Backtracking نمی‌کند). این ویژگی باعث می‌شود که برای جستجو در جریان‌های داده (Streams) که نمی‌توان به عقب برگشت (مثل داده‌های ورودی شبکه یا فایل‌های بزرگ)، ایده‌آل باشد.
#
# کاربردهای واقعی:
#
# تشخیص ویروس (اسکن امضای ویروس در فایل‌های اجرایی).
#
# جستجوی کلمات در ویرایشگرهای متن (مثل Ctrl+F در Notepad).
#
# تحلیل توالی‌های DNA در بیوانفورماتیک.
#
# پیاده‌سازی تابع strstr() در بسیاری از زبان‌ها (هرچند اغلب به دلیل سادگی از روش‌های دیگر مثل Two-Way استفاده می‌کنند).
#
# معایب اصلی: پیاده‌سازی و درک آن نسبت به روش ساده بسیار پیچیده‌تر است. همچنین در صورتی که الفبا (حروف) بسیار کوچک باشد یا الگو خیلی کوتاه، سربار (Overhead) ساخت LPS ممکن است از مزیت آن بیشتر شود (در آن موارد، روش ساده یا Boyer-Moore بهتر عمل می‌کنند).