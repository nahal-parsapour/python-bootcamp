#
# طرز کار به این صورت است که تعداد دفعات تکرار هر مقدار را می‌شمارد و سپس با استفاده از این شمارش‌ها، جایگاه نهایی هر عنصر را محاسبه می‌کند.
#
# مراحل گام‌به‌گام:
#
# پیدا کردن بازه: بیشترین و کمترین مقدار آرایه را پیدا می‌کنیم تا طول آرایه‌ی شمارنده را مشخص کنیم.
#
# شمارش (Counting): یک آرایه‌ی کمکی به نام Count به اندازه‌ی بازه ایجاد می‌کنیم. یک بار کل آرایه را پیمایش می‌کنیم و به ازای هر عدد، در خانه‌ی متناظر آن در Count یکی اضافه می‌کنیم. (حالا می‌دانیم هر عدد چند بار تکرار شده است).
#
# مجموع تجمعی (Prefix Sum): آرایه‌ی Count را طوری تغییر می‌دهیم که هر خانه، مجموع تعداد عناصر کوچک‌تر یا مساوی با آن اندیس را نشان دهد. این کار مشخص می‌کند که هر عدد در آرایه‌ی نهایی در چه جایگاهی باید قرار بگیرد.
#
# چیدمان نهایی (Placement): یک آرایه‌ی خروجی به همان اندازه‌ی آرایه‌ی اصلی ایجاد می‌کنیم. از آخرین عنصر آرایه‌ی اصلی شروع می‌کنیم به سمت چپ می‌رویم:
#
# عدد را برمی‌داریم.
#
# به آرایه‌ی Count می‌رویم و مقدار خانه‌ی متناظر آن عدد را می‌خوانیم.
#
# عدد را در آرایه‌ی خروجی، در اندیس (مقدار خوانده‌شده - 1) قرار می‌دهیم.
#
# سپس یک واحد از آن خانه‌ی Count کم می‌کنیم (تا اگر عدد تکراری داشت، دفعه‌ی بعدی در خانه‌ی قبلی قرار گیرد).
#
# در نهایت، آرایه‌ی خروجی را به جای آرایه‌ی اصلی کپی می‌کنیم.


# مرتبه‌ی زمانی (پیچیدگی): O(n + k) که n تعداد عناصر و k محدوده‌ی اعداد است. اگر k از n خیلی بزرگتر باشد، کارایی پایین می‌آید. اما اگر k نزدیک به n باشد، از همه‌ی الگوریتم‌های مقایسه‌ای سریع‌تر است.
#
# مرتبه‌ی حافظه (فضای اضافی): O(k) برای آرایه‌ی شمارنده، به علاوه O(n) برای آرایه‌ی خروجی، پس مجموعاً O(n + k) است.
#
# آیا پایدار (Stable) است؟ بله، به شرطی که آرایه را از انتها به ابتدا پیمایش کنیم. (همانطور که در مثال انجام دادیم). این ویژگی باعث می‌شود که ترتیب نسبی عناصر مساوی حفظ شود.
#
# محدودیت اصلی: فقط برای اعداد صحیح (یا داده‌هایی که قابل نگاشت به عدد صحیح هستند) در یک بازه‌ی مشخص کار می‌کند. برای اعداد اعشاری یا رشته‌ها به تنهایی قابل استفاده نیست (مگر با تکنیک‌های خاص مثل Radix Sort).
#
# مزیت اصلی: سرعت فوق‌العاده‌ی خطی (O(n) در عمل) برای داده‌های با بازه‌ی محدود. مثلاً برای مرتب‌سازی نمرات دانشجویان (۰ تا ۲۰) یا سن افراد (۰ تا ۱۵۰) بسیار ایده‌آل است.


