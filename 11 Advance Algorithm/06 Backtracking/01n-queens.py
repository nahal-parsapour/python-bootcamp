def solve_n_queens(n):
    board = [["." for _ in range(n)] for _ in range(n)]
    solutions = []

    def safe(r, c):
        for i in range(r):
            if board[i][c] == "Q":
                return False
        i, j = r-1, c-1
        while i >= 0 and j >= 0:
            if board[i][j] == "Q":
                return False
            i -= 1; j -= 1
        i, j = r-1, c+1
        while i >= 0 and j < n:
            if board[i][j] == "Q":
                return False
            i -= 1; j += 1
        return True

    def backtrack(r):
        if r == n:
            sol = [" ".join(row) for row in board]
            solutions.append(sol)
            return
        for c in range(n):
            if safe(r, c):
                board[r][c] = "Q"
                backtrack(r+1)
                board[r][c] = "."

    backtrack(0)
    return solutions

sol = solve_n_queens(4)
for s in sol:
    print("\n".join(s))
    print()
print("Total solutions:", len(sol))





def count_n_queens(n):
    board = ["."*n]
    cols = set()
    diag1 = set()
    diag2 = set()
    count = 0

    def backtrack(r):
        nonlocal count
        if r == n:
            count += 1
            return
        for c in range(n):
            if c not in cols and (r-c) not in diag1 and (r+c) not in diag2:
                cols.add(c); diag1.add(r-c); diag2.add(r+c)
                backtrack(r+1)
                cols.remove(c); diag1.remove(r-c); diag2.remove(r+c)

    backtrack(0)
    return count

