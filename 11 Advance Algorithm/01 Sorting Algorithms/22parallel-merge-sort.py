# Parallel Sorting Algorithms

from concurrent.futures import ThreadPoolExecutor

def merge(left, right):
    i = j = 0
    result = []
    while i < len(left) and j < len(right):
        if left[i] < right[j]:
            result.append(left[i]); i += 1
        else:
            result.append(right[j]); j += 1
    result.extend(left[i:])
    result.extend(right[j:])
    return result

def parallel_merge_sort(arr, depth=0, max_depth=2):
    if len(arr) <= 1:
        return arr
    mid = len(arr) // 2
    left = arr[:mid]
    right = arr[mid:]

    if depth < max_depth:
        with ThreadPoolExecutor(max_workers=2) as ex:
            left_sorted, right_sorted = list(ex.map(
                lambda x: parallel_merge_sort(x, depth+1, max_depth),
                [left, right]
            ))
    else:
        left_sorted = parallel_merge_sort(left, depth+1, max_depth)
        right_sorted = parallel_merge_sort(right, depth+1, max_depth)

    return merge(left_sorted, right_sorted)

arr = [5,3,8,4,2,9,1,7]
print(parallel_merge_sort(arr))




# تفاوت اصلی با Merge Sort معمولی
# در Merge Sort معمولی، تقسیم و ادغام به‌صورت ترتیبی (Sequential) و پشت‌سر هم انجام می‌شود: اول نیمه‌ی چپ کاملاً مرتب می‌شود، بعد نیمه‌ی راست، و در نهایت هر دو با هم ادغام می‌شوند.
# در Parallel Merge Sort، از چندین هسته‌ی پردازنده (یا چندین ماشین) برای انجام همزمان این کارها استفاده می‌کنیم. هدف اصلی این است که زمان اجرا را با تقسیم کار بین پردازنده‌ها به شدت کاهش دهیم.
#
# طرز کار Parallel Merge Sort
# الگوریتم از همان استراتژی «تقسیم و حکومت» استفاده می‌کند، اما با دو رویکرد اصلی برای موازی‌سازی:
#
# رویکرد اول: موازی‌سازی در مرحله‌ی تقسیم (موازی‌سازی بازگشتی)
# در این روش، هر بار که آرایه را به دو نیمه تقسیم می‌کنیم، دو هسته‌ی جداگانه را مسئول مرتب‌سازی هر نیمه می‌کنیم تا کارها همزمان انجام شوند.
#
# مرحله‌ی تقسیم موازی: یک ریسه (Thread) اصلی، آرایه را به دو بخش تقسیم می‌کند. سپس یک ریسه‌ی جدید برای مرتب‌سازی نیمه‌ی چپ ایجاد می‌کند، در حالی که خود ریسه‌ی اصلی (یا یک ریسه‌ی دیگر) به مرتب‌سازی نیمه‌ی راست می‌پردازد.
#
# این کار به‌صورت بازگشتی ادامه می‌یابد تا جایی که به تکه‌های بسیار کوچک برسیم.
#
# آستانه‌ی توقف (Threshold): برای جلوگیری از ایجاد هزاران ریسه (که باعث کندی سیستم می‌شود)، یک عدد آستانه تعریف می‌کنیم (مثلاً اگر اندازه‌ی آرایه از ۵۰۰۰ عنصر کمتر شد، دیگر ریسه‌ی جدید ایجاد نمی‌کنیم و آن بخش را با مرتب‌سازی درجی (Insertion Sort) یا همان Merge Sort معمولی (ترتیبی) مرتب می‌کنیم).
#
# مرحله‌ی ادغام (چالش اصلی): بعد از اینکه دو نیمه به‌طور موازی مرتب شدند، باید آن‌ها را با هم ادغام کنیم. این ادغام را یا به‌صورت ترتیبی (با یک هسته) انجام می‌دهیم (که گلوگاه خواهد بود)، یا خودِ عملیات ادغام را نیز به‌صورت موازی انجام می‌دهیم.
#
# رویکرد دوم: موازی‌سازی در مرحله‌ی ادغام (ادغام موازی با جستجوی دودویی)
# برای این که ادغام هم موازی شود، از یک تکنیک هوشمندانه استفاده می‌کنیم:
#
# فرض کنید دو آرایه‌ی مرتب A و B را می‌خواهیم در آرایه‌ی خروجی C ادغام کنیم.
#
# به جای اینکه یک هسته تک‌تک عناصر را مقایسه کند، آرایه‌ی خروجی C را به P بخش مساوی (تعداد هسته‌ها) تقسیم می‌کنیم.
#
# برای هر هسته، نقطه‌ی شروع و پایان آن را در C مشخص می‌کنیم. سپس با استفاده از جستجوی دودویی (Binary Search)، مشخص می‌کنیم که دقیقاً از آرایه‌ی A و آرایه‌ی B چه تعداد عنصر باید در آن بازه قرار بگیرند. (مثلاً برای بخش دوم C، می‌دانیم که ۱۰۰ عنصر از A و ۵۰ عنصر از B باید بیایند).
#
# حالا هر هسته به‌طور کاملاً مستقل، بخش مربوط به خود را از A و B برداشته، مقایسه کرده و در جای خود در C می‌نویسد.


# مرتبه‌ی زمانی (پیچیدگی):
#
# اگر P هسته‌ی پردازشی داشته باشیم، در حالت ایده‌آل (و با ادغام موازی)، زمان اجرا به حدود O((n/P) log(n/P) + n) یا دقیق‌تر O((n/P) log n) کاهش می‌یابد. اما در عمل، به خاطر سربار ایجاد ریسه‌ها و همگام‌سازی (Synchronization)، سرعت به‌صورت خطی افزایش نمی‌یابد و معمولاً به حدود n log n / P نزدیک می‌شود.
#
# مرتبه‌ی حافظه (فضای اضافی): مانند Merge Sort معمولی، به O(n) حافظه‌ی اضافی (آرایه‌ی کمکی) نیاز دارد، مگر اینکه از نسخه‌های درجای (In-place) خاص استفاده شود (که در موازی بسیار نادر و پیچیده است).
#
# آیا پایدار (Stable) است؟ بله. شرط برابری در ادغام (حتی در حالت موازی با جستجوی دودویی) به‌گونه‌ای طراحی می‌شود که ترتیب نسبی عناصر مساوی حفظ گردد.
#
# مزیت اصلی: استفاده‌ی بهینه از پردازنده‌های چند هسته‌ای (CPU) و پردازنده‌های گرافیکی (GPU). برای آرایه‌های بسیار بزرگ (میلیاردها عنصر)، تفاوت سرعت با حالت ترتیبی چشمگیر است.
#
# معایب اصلی (چالش‌ها):
#
# سربار (Overhead) ریسه‌ها: اگر آرایه کوچک باشد، هزینه‌ی ایجاد و مدیریت ریسه‌ها از مزیت موازی‌سازی بیشتر می‌شود. (به همین دلیل از آستانه استفاده می‌کنیم).
#
# گلوگاه ادغام: اگر ادغام نهایی را به‌صورت ترتیبی انجام دهیم، عملاً موازی‌سازی بی‌اثر می‌شود. بنابراین پیاده‌سازی ادغام موازی با جستجوی دودویی ضروری است اما بسیار پیچیده‌تر است.
#
# کش (Cache) پردازنده: در حالت موازی، ممکن است هسته‌های مختلف روی بخش‌هایی از حافظه کار کنند که در کش همدیگر نیستند (Cache Coherency) که خود باعث کاهش سرعت می‌شود.
#
