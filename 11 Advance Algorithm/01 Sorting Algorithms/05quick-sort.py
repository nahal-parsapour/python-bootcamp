# ایده‌ی اصلی این الگوریتم نیز مانند Merge Sort، «تقسیم و حکومت» (Divide and Conquer) است، اما با یک تفاوت کلیدی: به جای تقسیم کردن به دو نیمه‌ی مساوی، یک عنصر محوری (Pivot) انتخاب می‌کند و آرایه را حول آن محور بازچینی (Partition) می‌کند.
#
# این الگوریتم کاملاً بازگشتی (Recursive) است و سه مرحله‌ی اصلی دارد:
#
# مرحله‌ی ۱: انتخاب محور (Pivot Selection)
# یک عنصر از آرایه را به عنوان محور انتخاب می‌کنیم. روش‌های مختلفی دارد:
#
# انتخاب اولین عنصر.
#
# انتخاب آخرین عنصر (رایج‌ترین).
#
# انتخاب عنصر وسط.
#
# انتخاب تصادفی (Random Pivot) برای جلوگیری از بدترین حالت.
#
# مرحله‌ی ۲: بازچینی (Partitioning)
# آرایه را طوری مرتب می‌کنیم که:
#
# همه‌ی عناصر کوچک‌تر از محور به سمت چپ محور بروند.
#
# همه‌ی عناصر بزرگ‌تر از محور به سمت راست محور بروند.
#
# خود محور در جای نهایی‌اش در آرایه قرار می‌گیرد.
#
# مرحله‌ی ۳: بازگشت (Recursion)
# حالا آرایه به دو بخش (چپ و راست محور) تقسیم شده است. همین کار (انتخاب محور و بازچینی) را به صورت بازگشتی برای هر دو بخش انجام می‌دهیم تا همه‌ی جایگاه‌ها مشخص شوند.



# مرتبه‌ی زمانی (پیچیدگی):
#
# حالت متوسط و بهترین: O(n log n) — چون معمولاً محور آرایه را به دو بخش نسبتاً مساوی تقسیم می‌کند.
#
# بدترین حالت: O(n²) — زمانی رخ می‌دهد که محور همیشه کوچک‌ترین یا بزرگ‌ترین عنصر باشد (مثلاً آرایه از قبل مرتب باشد و ما اولین یا آخرین عنصر را محور انتخاب کنیم). این مشکل با انتخاب محور تصادفی یا «میانگین سه‌تایی» (Median-of-Three) حل می‌شود.
#
# مرتبه‌ی حافظه (فضای اضافی): O(log n) — فقط برای پشته‌ی بازگشت (Recursion Stack) نیاز به حافظه دارد، چون خود عملیات بازچینی درجا (In-place) انجام می‌شود و حافظه‌ی اضافی مثل Merge Sort مصرف نمی‌کند.
#
# آیا پایدار (Stable) است؟ خیر. چون در مرحله‌ی بازچینی، عناصر را با جابه‌جایی (Swap) به سمت چپ و راست می‌فرستیم، ترتیب نسبی عناصر مساوی به هم می‌ریزد.
#
# مزیت اصلی: سریع‌ترین الگوریتم مرتب‌سازی در عمل برای داده‌های بزرگ است. چون درجا کار می‌کند، از حافظه‌ی کش (Cache) پردازنده خیلی خوب استفاده می‌کند و ضریب ثابت (Constant Factor) پایینی دارد. به همین دلیل، تابع sort() در بسیاری از زبان‌های برنامه‌نویسی (مثل C++ و Python) در پشت‌صحنه از Quick Sort یا ترکیبی از آن استفاده می‌کنند.



