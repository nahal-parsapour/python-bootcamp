def cocktail_shaker_sort(arr):
    n = len(arr)
    start = 0
    end = n - 1
    swaps = 0

    while True:
        swapped = False
        print(f"\nForward pass (start={start}, end={end}):")
        for i in range(start, end):
            print(f"Compare {arr[i]} and {arr[i+1]}")
            if arr[i] > arr[i + 1]:
                print(f" Swap {arr[i]} <-> {arr[i+1]}")
                arr[i], arr[i+1] = arr[i+1], arr[i]
                swaps += 1
                swapped = True

        if not swapped:
            break

        swapped = False
        end -= 1

        print(f"\nBackward pass (start={start}, end={end}):")
        for i in range(end, start, -1):
            print(f"Compare {arr[i-1]} and {arr[i]}")
            if arr[i - 1] > arr[i]:
                print(f" Swap {arr[i-1]} and {arr[i]}")
                arr[i - 1], arr[i] = arr[i], arr[i - 1]
                swaps += 1
                swapped = True

        start += 1

        if not swapped:
            break

    print("\nFinal array:", arr)
    print("Total swaps:", swaps)
    return arr, swaps

arr = [5, 3, 8, 4, 0, 2]
cocktail_shaker_sort(arr)




