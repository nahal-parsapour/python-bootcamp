# طرز کار Interpolation Search
# ایده‌ی اصلی این الگوریتم، جستجوی هوشمندانه‌تر از جستجوی دودویی (Binary Search) است.
# در جستجوی دودویی، ما همیشه وسط بازه را بررسی می‌کنیم (mid = (low + high) / 2). اما در جستجوی درونیابی، از مقدار خود عناصر برای حدس زدن موقعیت دقیق‌تر هدف استفاده می‌کنیم. این کار دقیقاً شبیه به جستجوی یک کلمه در فرهنگ لغت است: اگر به دنبال کلمه‌ی «آب» هستید، کتاب را از اول باز می‌کنید، نه از وسط. اگر به دنبال «یزد» هستید، کتاب را از آخر باز می‌کنید.
#
# الگوریتم فرض می‌کند که داده‌ها به‌طور یکنواخت (Uniformly) توزیع شده‌اند. بر اساس این فرض، با استفاده از یک فرمول، موقعیت محتمل‌ترین جایگاه هدف را محاسبه می‌کند.

# مراحل گام‌به‌گام (برای آرایه‌ی صعودی):
#
# low = 0 و high = n-1 را تنظیم کنید.
#
# تا وقتی که low <= high و target بین arr[low] و arr[high] باشد، مرحله‌ی ۳ را تکرار کنید (اگر هدف از محدوده خارج باشد، جستجو بی‌نتیجه است).
#
# با استفاده از فرمول بالا، موقعیت حدسی pos را محاسبه کنید.
#
# مقدار arr[pos] را با target مقایسه کنید:
#
# اگر arr[pos] == target → جستجو موفق بود. اندیس pos را برگردانید.
#
# اگر arr[pos] > target → هدف در سمت چپ است. پس high = pos - 1 کنید.
#
# اگر arr[pos] < target → هدف در سمت راست است. پس low = pos + 1 کنید.
#
# اگر حلقه تمام شد و هدف پیدا نشد، یعنی عنصر در آرایه وجود ندارد. مقدار -1 را برگردانید.




# مرتبه‌ی زمانی (پیچیدگی):
#
# بهترین و متوسط حالت (داده‌های یکنواخت): O(log log n) — که از O(log n) بسیار سریع‌تر است! (برای ۱ میلیارد عنصر، به جای ۳۰ مرحله، فقط حدود ۵ مرحله نیاز دارد).
#
# بدترین حالت (داده‌های غیریکنواخت یا نمایی): O(n) — مثلاً اگر اعداد به‌صورت [1, 2, 4, 8, 16, 32, ...] باشند، فرمول درونیابی کاملاً بی‌اثر می‌شود و ممکن است به جستجوی خطی تبدیل شود.
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — کاملاً درجا است و هیچ حافظه‌ی اضافی مصرف نمی‌کند.
#
# پیش‌نیاز اصلی:
#
# آرایه باید مرتب (Sorted) باشد.
# بهترین عملکرد زمانی است که داده‌ها توزیع یکنواخت (Uniform Distribution) داشته باشند.
# آیا می‌توان روی لیست پیوندی اجرا کرد؟ خیر، به همان دلیل جستجوی دودویی؛ نیاز به دسترسی تصادفی (Random Access) با اندیس دارد.
#
# مزیت اصلی: اگر داده‌های شما یکنواخت هستند (مثلاً نمرات دانشجویان، سن افراد، یا شماره‌های پرسنلی که پشت سر هم صادر شده‌اند)، این الگوریتم از جستجوی دودویی به مراتب سریع‌تر است.
#
# معایب اصلی (مهم): اگر داده‌ها یکنواخت نباشند، عملکرد آن به شدت افت می‌کند و ممکن است از جستجوی خطی هم بدتر شود. همچنین محاسبات فرمول آن شامل تقسیم و ضرب اعشاری است که نسبت به جستجوی دودویی (که فقط جمع و تقسیم بر ۲ دارد) سنگین‌تر است. به همین دلیل، بسیاری از کتابخانه‌های استاندارد به جای آن از Binary Search استفاده می‌کنند تا عملکردی تضمین‌شده داشته باشند.

