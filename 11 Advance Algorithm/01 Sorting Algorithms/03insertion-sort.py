def insertion_sort(arr):
    comparisons = 0
    shifts = 0

    for i in range(1, len(arr)):
        key = arr[i]
        j = i - 1

        while j >= 0:
            if arr[j] > key:
                arr[j+1] = arr[j]
                shifts += 1
                j -= 1
            else:
                break

        arr[j+1] = key

    return arr, comparisons, shifts

print(insertion_sort([5, 3, 8, 0, 4, 2]))


# binary:
def binary_search(arr, key, start, end):
    while start <= end:
        mid = (start + end) // 2
        if arr[mid] < key:
            start = mid + 1
        else:
            end = mid - 1
    return start

def binary_insertion_sort(arr):
    for i in range(1, len(arr)):
        key = arr[i]
        pos = binary_search(arr, key, 0, i-1)
        arr[pos+1:i+1] = arr[pos:i]
        arr[pos] = key
    return arr

print(binary_insertion_sort([5, 3, 8, 0, 4, 2]))




# طرز کار Insertion Sort
# ایده‌ی اصلی این الگوریتم دقیقاً مثل دسته‌بندی کردن کارت‌های بازی در دستتان است:
# کارت جدید را از سمت راست بردارید و در جای درست، بین کارت‌های مرتب‌شده‌ی سمت چپ قرار دهید.
#
# الگوریتم لیست را به دو بخش فرضی تقسیم می‌کند:
#
# بخش چپ: مرتب‌شده (در ابتدا فقط شامل اولین عنصر است).
#
# بخش راست: مرتب‌نشده (بقیه‌ی عناصر).
#
# مراحل گام‌به‌گام:
#
# فرض کنید اولین عنصر (خانه‌ی ۰) به تنهایی یک بخش مرتب‌شده است.
#
# اولین عنصر از بخش مرتب‌نشده (خانه‌ی ۱) را بردارید و در یک متغیر موقت ذخیره کنید.
#
# این عنصر را با عناصر بخش مرتب‌شده (سمت چپ) مقایسه کنید، از نزدیک‌ترینشان به سمت چپ‌ترین شروع کنید.

# تا وقتی که به ابتدای آرایه نرسیده‌اید و عنصر چپ‌تان از عنصر ذخیره‌شده بزرگ‌تر است، آن عنصر چپ را یک خانه به سمت راست شیفت دهید (جا باز کنید).
#
# به محض اینکه به عنصری رسیدید که از عنصر ذخیره‌شده کوچک‌تر یا مساوی است، عنصر ذخیره‌شده را در خانه‌ی خالی‌شده قرار دهید.
#
# حالا بخش مرتب‌شده یک خانه بزرگتر شده است. مرحله ۲ تا ۵ را برای تمام عناصر باقیمانده‌ی بخش مرتب‌نشده تکرار کنید.


# مرتبه‌ی زمانی (پیچیدگی):
#
# حالت متوسط و بدترین (آرایهٔ نزولی): O(n²)
#
# بهترین حالت (آرایه از قبل مرتب): O(n) — چون هر بار فقط یک مقایسه می‌کند و می‌بیند که عنصر قبلی کوچک‌تر است، پس بدون جابه‌جایی جلو می‌رود.
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — چون همه‌ی کارها را درون خود آرایه (In-place) و فقط با یک متغیر موقت انجام می‌دهد.
#
# آیا پایدار (Stable) است؟ بله. اگر دو عدد مساوی داشته باشیم، شرط جابه‌جایی فقط برای «بزرگ‌تر» است، پس عنصر جدید را بعد از عناصر مساوی قبلی قرار می‌دهد و ترتیب نسبی حفظ می‌شود.
#
# مزیت مهم: این الگوریتم برای داده‌های کوچک یا آرایه‌هایی که تقریباً مرتب هستند، فوق‌العاده سریع عمل می‌کند (حتی از بسیاری از الگوریتم‌های پیشرفته‌تر در این شرایط بهتر است). به همین دلیل در بسیاری از زبان‌های برنامه‌نویسی، در پشت‌صحنه‌ی الگوریتم‌های پیشرفته‌تر (مثل Quick Sort) وقتی داده کوچک می‌شود، از Insertion Sort استفاده می‌کنند.




# طرز کار Binary Insertion Sort
# این الگوریتم درست مانند Insertion Sort عمل می‌کند، با یک تفاوت بسیار مهم در نحوه‌ی پیدا کردن جای درست برای عنصر جدید.
#
# در Insertion Sort معمولی، برای پیدا کردن جای عنصر جدید، از آخر بخش مرتب‌شده شروع می‌کردیم و یکی‌یکی به عقب می‌رفتیم (جستجوی خطی - Linear Search).
#
# در Binary Insertion Sort، برای پیدا کردن جای عنصر جدید، از جستجوی دودویی (Binary Search) روی بخش مرتب‌شده استفاده می‌کنیم.
#
# چون بخش چپ (مرتب‌شده) یک آرایه‌ی مرتب است، می‌توانیم با استفاده از Binary Search، جای درست را خیلی سریع‌تر پیدا کنیم (در تعداد مراحل کمتر).
#
# مراحل گام‌به‌گام:
#
# مثل قبل، اولین عنصر (خانه‌ی ۰) را به تنهایی یک بخش مرتب‌شده در نظر بگیرید.
#
# اولین عنصر از بخش مرتب‌نشده (خانه‌ی ۱) را بردارید و در متغیر key ذخیره کنید.
#
# مرحله‌ی جستجو با باینری: در بخش مرتب‌شده (سمت چپ)، با استفاده از جستجوی دودویی، موقعیتی را پیدا کنید که key باید در آن قرار بگیرد. (یعنی اولین جایی که عنصر آن از key بزرگ‌تر یا مساوی است).
#
# مرحله‌ی جابه‌جایی (شیفت): همه‌ی عناصر از آن موقعیت پیدا‌شده تا انتهای بخش مرتب‌شده را یک خانه به سمت راست شیفت دهید تا جا باز شود.
#
# عنصر key را در خانه‌ی خالی‌شده قرار دهید.
#
# این کار را برای تمام عناصر باقیمانده‌ی بخش مرتب‌نشده تکرار کنید.


# تعداد مقایسه‌ها (Comparisons): از O(n²) در حالت معمولی به O(n log n) کاهش پیدا کرده است، چون جستجوی جای درست با باینری انجام می‌شود.
#
# تعداد جابه‌جایی‌ها (Shifts/Swaps): تغییری نکرده است و همچنان O(n²) است. چون برای جا باز کردن، همچنان باید عناصر را یکی‌یکی به سمت راست شیفت دهیم. بنابراین مرتبه‌ی زمانی کل الگوریتم هنوز O(n²) است (چون عمل شیفت از عمل مقایسه سنگین‌تر است).
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — همچنان درجا (In-place) است.
#
# آیا پایدار (Stable) است؟ بله. در پیاده‌سازی صحیح، جستجوی دودویی به گونه‌ای انجام می‌شود که اولین عنصر بزرگ‌تر از key را پیدا کند (نه بزرگ‌تر یا مساوی). در نتیجه، عناصر مساوی قبلی جابه‌جا نمی‌شوند و ترتیب نسبی حفظ می‌گردد.
#
# چه زمانی به کار می‌آید؟ وقتی که عملیات مقایسه کردن بسیار گران‌قیمت باشد (مثلاً مقایسه‌ی رشته‌های خیلی طولانی یا اشیاء سنگین)، این الگوریتم نسبت به Insertion Sort معمولی سریع‌تر است، چون تعداد مقایسه‌ها را به شدت کاهش می‌دهد. اما اگر عملیات شیفت دادن گران‌قیمت باشد، تفاوتی با حالت معمولی ندارد.
