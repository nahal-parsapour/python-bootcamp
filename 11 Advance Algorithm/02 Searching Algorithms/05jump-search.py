import math

arr = list(range(1, 501))
target = 377

def jump_search(arr, target, block):
    n = len(arr)
    step = block
    prev = 0
    jumps = 0

    while prev < n and arr[min(step, n)-1] < target:
        jumps += 1
        prev = step
        step += block

    linear_checks = 0
    while prev < n and arr[prev] < target:
        linear_checks += 1
        prev += 1

    return jumps, linear_checks

for b in [10, 20, 30]:
    j, l = jump_search(arr, target, b)
    print(f"Block{b}: jumps={j}, linear checks={l}")


def best_block(arr, target):
    best = None
    best_cost = float('inf')

    for b in range(5, 60):
        j, l = jump_search(arr, target, b)
        cost = j + l
        if cost < best_cost:
            best_cost = cost
            best = b

    return best

print("best block:", best_block(arr, 377))




# طرز کار Jump Search
# ایده‌ی اصلی این الگوریتم، ترکیبی از جستجوی خطی و جستجوی دودویی است، اما با یک رویکرد خاص: به جای بررسی تک‌تک عناصر (مثل Linear Search) یا نصف‌کردن مداوم بازه (مثل Binary Search)، با گام‌های ثابت و بزرگ به جلو می‌پریم تا جایی که از مقدار موردنظر عبور کنیم، سپس در همان بلوک (بازه‌ی کوچک) به‌صورت خطی به دنبال هدف می‌گردیم.
#
# مهم‌ترین نکته در این الگوریتم، انتخاب اندازه‌ی گام (Step Size) است. اندازه‌ی گام بهینه، جذر تعداد عناصر (√n) است. با این اندازه، تعادل بین تعداد پرش‌ها و تعداد جستجوهای خطی به بهترین شکل ممکن می‌رسد.
#
# مراحل گام‌به‌گام (برای آرایه‌ی صعودی):
#
# طول آرایه (n) را محاسبه کرده و اندازه‌ی گام را مشخص کنید: step = √n.
#
# از ابتدای آرایه (index = 0) شروع کنید.
#
# تا وقتی که index از انتهای آرایه کمتر است و arr[index] < target (هدف از عنصر جاری بزرگ‌تر است)، به اندازه‌ی step به جلو بپرید: index = index + step.
#
# حالا یا به انتهای آرایه رسیده‌اید، یا به عنصری رسیده‌اید که از هدف بزرگ‌تر یا مساوی است.
# نقطه‌ی شروع بلوک قبلی را مشخص کنید: prev = index - step.
#
# یک جستجوی خطی (Linear Search) از prev تا min(index, n-1) انجام دهید تا هدف را پیدا کنید.
#
# اگر پیدا شد، اندیس آن را برگردانید. در غیر این صورت، یعنی هدف در آرایه وجود ندارد و مقدار -1 را برگردانید.


# مرتبه‌ی زمانی (پیچیدگی):
#
# بهترین، متوسط و بدترین حالت: O(√n) — چون تعداد پرش‌ها n/step و تعداد جستجوهای خطی در بلوک نهایی step است. با بهینه‌سازی step = √n، مجموع به O(√n + √n) = O(√n) می‌رسد.
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — هیچ حافظه‌ی اضافی مصرف نمی‌کند.
#
# پیش‌نیاز اصلی: آرایه باید مرتب (Sorted) باشد.
#
# مقایسه با Binary Search: از نظر سرعت نظری، Binary Search (O(log n)) از Jump Search سریع‌تر است. اما Jump Search یک مزیت مهم دارد: فقط به سمت جلو حرکت می‌کند (Forward-Only). این ویژگی باعث می‌شود برای لیست‌های پیوندی (Linked Lists) که دسترسی تصادفی ندارند و پیمایش عقب‌گرد در آن‌ها گران است، بسیار مناسب‌تر از Binary Search باشد (چون Binary Search مدام به عقب و جلو می‌پرد).
#
# مزیت اصلی: پیاده‌سازی آن از Binary Search ساده‌تر است و برای آرایه‌های بسیار بزرگ که دسترسی به عنصر وسط (محاسبه‌ی دقیق mid) ممکن است هزینه‌بر باشد (مثلاً در حافظه‌های خارجی)، انتخاب بهتری نسبت به Linear Search محسوب می‌شود.
#
# معایب اصلی:
#
# از Binary Search کندتر است، مگر در شرایط خاص (مثل لیست‌های پیوندی یا سیستم‌هایی که حرکت عقب‌گرد ممنوع است).
#
# اگر اندازه‌ی گام را اشتباه انتخاب کنید (خیلی بزرگ یا خیلی کوچک)، کارایی به شدت کاهش می‌یابد و ممکن است از Linear Search هم بدتر شود.