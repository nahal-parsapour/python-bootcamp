from collections import deque

graph = {
    "A": ["B", "C"],
    "B": ["D", "E"],
    "C": ["F"],
    "D": ["G"],
    "E": ["G"],
    "F": ["E"],
    "G": ["H"],
    "H": []
}

def bfs_shortest_path(graph, start, goal):
    queue = deque([(start, [start])])
    visited = {start}

    while queue:
        node, path = queue.popleft()
        if node == goal:
            return path
        for neighbor in graph[node]:
            if neighbor not in visited:
                visited.add(neighbor)
                queue.append((neighbor, path + [neighbor]))
    return None

path = bfs_shortest_path(graph, "A", "H")
print(" → ".join(path))





def all_pairs_shortest_paths(graph):
    nodes = list(graph.keys())
    result = {}
    for s in nodes:
        for t in nodes:
            if s == t:
                continue
            path = bfs_shortest_path(graph, s, t)
            result[(s, t)] = path
    return result

pairs = all_pairs_shortest_paths(graph)
for (s, t), p in pairs.items():
    print(f"{s} → {t}: {(' → '.join(p)) if p else 'No path'}")







#
# طرز کار BFS
# ایده‌ی اصلی این الگوریتم، پیمایش لایه‌به‌لایه (یا سطح‌به‌سطح) در گراف یا درخت است.
# فرض کنید یک سنگ در آب انداخته‌اید؛ امواج به صورت دایره‌های متحدالمرکز از مرکز به سمت بیرون حرکت می‌کنند. BFS دقیقاً به همین شکل عمل می‌کند: از گره‌ی شروع (ریشه) حرکت می‌کند، اول همه‌ی همسایه‌های مستقیم آن را ملاقات می‌کند، سپس همسایه‌های همسایه‌ها را، و الی آخر.
#
# برای این کار، BFS از یک صف (Queue) با قاعده‌ی «اولین ورودی، اولین خروجی» (FIFO) استفاده می‌کند تا ترتیب بازدید را مدیریت کند. همچنین برای جلوگیری از رفتن به حلقه‌های بی‌نهایت (در گراف‌های با دور)، یک مجموعه (یا آرایه) برای مشخص‌کردن گره‌های ملاقات‌شده (Visited) نگهداری می‌کند.
#
# مراحل گام‌به‌گام (در گراف):
#
# گره‌ی شروع (Start Node) را در صف قرار دهید و آن را به عنوان ملاقات‌شده (Visited) علامت‌گذاری کنید.
#
# تا زمانی که صف خالی نشده است، مراحل زیر را تکرار کنید:
#
# یک گره را از جلوی صف خارج کنید (Dequeue). این گره، گره‌ی جاری شماست.
#
# گره‌ی جاری را پردازش کنید (مثلاً چاپ کنید یا در خروجی ذخیره کنید).
#
# همه‌ی همسایه‌های (Neighbors) گره‌ی جاری را بررسی کنید:
#
# اگر همسایه‌ای قبلاً ملاقات نشده بود، آن را به انتهای صف اضافه کنید (Enqueue) و آن را به عنوان ملاقات‌شده علامت‌گذاری کنید.
#
# وقتی صف خالی شد، یعنی تمام گره‌های قابل‌دسترس را پیمایش کرده‌اید.




# مرتبه‌ی زمانی (پیچیدگی): O(V + E) که V تعداد رأس‌ها (Vertices) و E تعداد یال‌ها (Edges) است. چون هر رأس دقیقاً یک بار وارد صف می‌شود و هر یال دقیقاً یک بار بررسی می‌شود.
#
# مرتبه‌ی حافظه (فضای اضافی): O(V) — زیرا در بدترین حالت، صف ممکن است همه‌ی رأس‌ها را در خود نگه دارد. همچنین نیاز به آرایه‌ی Visited به اندازه‌ی V داریم.
#
# پیمایش درخت: اگر روی درخت اجرا شود (که دور ندارد)، دیگر نیازی به آرایه‌ی Visited نیست (چون هر گره فقط یک والد دارد)، اما برای ایمنی و سادگی معمولاً نگه داشته می‌شود.
#
# آیا کامل (Complete) است؟ بله. اگر جوابی در گراف وجود داشته باشد، BFS آن را پیدا می‌کند (در گراف‌های متناهی).
#
# مهم‌ترین ویژگی (کاربرد اصلی): یافتن کوتاه‌ترین مسیر در گراف‌های بدون وزن
# چون BFS لایه‌به‌لایه جلو می‌رود، اولین باری که به یک گره می‌رسد، کوتاه‌ترین فاصله (از نظر تعداد یال) از مبدأ تا آن گره است.
#
# ساختار داده‌ی کلیدی: صف (Queue). اگر از پشته (Stack) استفاده می‌کردیم، الگوریتم به DFS (جستجوی عمق‌اول) تبدیل می‌شد.
#
# کاربردهای واقعی:
#
# پیدا کردن کوتاه‌ترین مسیر در نقشه‌ها (مثل مسیریابی GPS).
#
# خزیدن وب (Web Crawling) برای ایندکس کردن صفحات.
#
# پیدا کردن مؤلفه‌های همبند (Connected Components) در شبکه‌های اجتماعی.
#
