import random

def max_activities_random(n=20):
    arr = []
    for _ in range(n):
        start = random.randint(0, 20)
        finish = start + random.randint(1, 10)
        arr.append((start, finish))

    arr = sorted(arr, key=lambda x: x[1])

    count = 0
    last = -1
    for s, f in arr:
        if s >= last:
            count += 1
            last = f
    return count

print(max_activities_random())




# طرز کار الگوریتم (روش حریصانه - Greedy)
# ایده‌ی اصلی این الگوریتم فوق‌العاده ساده و هوشمندانه است:
# همیشه فعالیتی را انتخاب کن که زودتر از همه تمام می‌شود.
# چون با این کار، حداکثر فضای خالی را برای فعالیت‌های بعدی باقی می‌گذاریم و شانس انتخاب تعداد بیشتری فعالیت را افزایش می‌دهیم.
#
# مراحل گام‌به‌گام:
#
# مرتب‌سازی (پیش‌نیاز): تمام فعالیت‌ها را بر اساس زمان پایان (Finish Time) به ترتیب صعودی (از زودترین به دیرترین) مرتب کنید.
#
# انتخاب اول: اولین فعالیت در لیست مرتب‌شده (یعنی فعالیتی که زودترین زمان پایان را دارد) را انتخاب کنید. زمان پایان آن را به عنوان last_finish ذخیره کنید.
#
# پیمایش و انتخاب: از دومین فعالیت تا آخرین فعالیت در لیست مرتب‌شده، به ترتیب جلو بروید:
#
# اگر زمان شروع فعالیت جاری، بزرگ‌تر یا مساوی (>=) با last_finish بود، یعنی با فعالیت قبلی انتخاب‌شده تداخل ندارد.
#
# پس این فعالیت را انتخاب کنید و last_finish را به‌روزرسانی کنید (یعنی برابر با زمان پایان این فعالیت جدید قرار دهید).
#
# در غیر این صورت، فعالیت جاری را نادیده بگیرید و به سراغ بعدی بروید.
#
# پایان کار: وقتی همه‌ی فعالیت‌ها را بررسی کردید، لیست فعالیت‌های انتخاب‌شده، بیش‌ترین تعداد ممکن را دارند.



# مرتبه‌ی زمانی (پیچیدگی):
#
# مرتب‌سازی: O(n log n)
#
# پیمایش و انتخاب: O(n)
#
# مجموعاً: O(n log n)
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — به شرطی که بتوانیم فعالیت‌ها را در همان آرایه مرتب کنیم و فقط از چند متغیر ساده (last_finish و شمارنده) استفاده کنیم.
#
# دلیل درستی (چرا همیشه جواب بهینه می‌دهد؟): این الگوریتم از اصل «انتخاب حریصانه» (Greedy Choice Property) و «ساختار بهینه‌ی زیرمسئله» (Optimal Substructure) پیروی می‌کند. اثبات ریاضی آن نشان می‌دهد که همیشه یک جواب بهینه وجود دارد که شامل فعالیت با زودترین زمان پایان است. پس حذف بقیه و ادامه‌ی کار، جواب نهایی را از دست نمی‌دهد.
#
# پیش‌نیاز اصلی: فعالیت‌ها باید بر اساس زمان پایان مرتب شوند. اگر نباشند، الگوریتم جواب اشتباه می‌دهد.
#
# نسخه‌های مختلف: اگر فعالیت‌ها بر اساس زمان شروع مرتب شوند یا اگر هدف بیشینه‌کردن طول زمان اشغال سالن باشد (به جای تعداد فعالیت‌ها)، این الگوریتم حریصانه جواب نمی‌دهد و باید از برنامه‌ریزی پویا (Dynamic Programming) استفاده کرد.
#
# کاربرد واقعی: مدیریت زمان‌بندی پردازنده‌ها (CPU Scheduling)، انتخاب جلسات در تقویم، تخصیص کلاس‌های درس به اساتید، و حل مسائل بهینه‌سازی در شبکه‌های کامپیوتری.