import heapq

graph = {
    "A": [("B", 4), ("C", 2)],
    "B": [("D", 5)],
    "C": [("B", 1), ("D", 8)],
    "D": [("E", 6)],
    "E": []
}

def dijkstra(graph, start):
    dist = {node: float("inf") for node in graph}
    prev = {node: None for node in graph}
    dist[start] = 0
    pq = [(0, start)]

    while pq:
        d, u = heapq.heappop(pq)
        if d > dist[u]:
            continue
        for v, w in graph[u]:
            nd = d + w
            if nd < dist[v]:
                dist[v] = nd
                prev[v] = u
                heapq.heappush(pq, (nd, v))
    return dist, prev

dist, prev = dijkstra(graph, "A")

def build_path(prev, target):
    path = []
    cur = target
    while cur is not None:
        path.append(cur)
        cur = prev[cur]
    return list(reversed(path))

path = build_path(prev, "E")
print("Path:", " → ".join(path))
print("Cost =", dist["E"])



for node in graph:
    if node == "A":
        continue
    p = build_path(prev, node)
    print(f"A → {node}: {' → '.join(p)}, cost = {dist[node]}")





# الگوریتم دیکسترا برای پیدا کردن کوتاه‌ترین مسیر (کم‌هزینه‌ترین مسیر) از یک گره‌ی مبدأ (Source) به همه‌ی گره‌های دیگر در یک گراف وزن‌دار (دارای یال‌های با هزینه) استفاده می‌شود.
# فقط و فقط در صورتی کار می‌کند که همه‌ی وزن‌های یال‌ها، نامنفی (≥ 0) باشند.
#
# طرز کار الگوریتم (روش حریصانه - Greedy)
# ایده‌ی اصلی دیکسترا فوق‌العاده ساده است:
# همیشه گره‌ای را انتخاب کن که در حال حاضر کمترین فاصله را از مبدأ دارد، و مطمئن باش که دیگر نمی‌توانی کوتاه‌تر از این برایش پیدا کنی.
# سپس از آن گره برای به‌روزرسانی (Relaxation) فاصله‌ی همسایه‌هایش استفاده می‌کند.
#
# برای مدیریت این کار، الگوریتم از یک صف اولویت (Priority Queue) یا هیپ مینیمم (Min-Heap) استفاده می‌کند تا همیشه گره‌ی با کمترین فاصله را به‌سرعت پیدا کند.
#
# مراحل گام‌به‌گام:
#
# مقداردهی اولیه:
#
# یک آرایه به نام dist به اندازه‌ی تعداد گره‌ها در نظر بگیرید. فاصله‌ی مبدأ را 0 و فاصله‌ی بقیه را ∞ (بی‌نهایت) قرار دهید.
#
# گره‌ی مبدأ را با فاصله‌ی 0 در صف اولویت (هیپ) قرار دهید.
#
# پیمایش اصلی: تا زمانی که صف اولویت خالی نشده است:
#
# گره‌ای که کمترین فاصله را در هیپ دارد، خارج کنید (Pop). به این گره، گره‌ی جاری می‌گوییم.
#
# اگر این گره قبلاً پردازش شده (یا فاصله‌اش در هیپ قدیمی باشد)، آن را نادیده بگیرید.
#
# برای همه‌ی همسایه‌های این گره‌ی جاری:
#
# فاصله‌ی جدید = dist[گره‌ی جاری] + وزن یال بین آن‌ها.
#
# اگر این فاصله‌ی جدید از dist[همسایه] کوچک‌تر بود، یعنی مسیر بهتری پیدا کرده‌ایم. پس dist[همسایه] را با این مقدار جدید به‌روزرسانی کرده و آن همسایه را با فاصله‌ی جدید در هیپ قرار می‌دهیم.
#
# پایان: وقتی صف خالی شد، آرایه‌ی dist شامل کوتاه‌ترین فاصله از مبدأ تا همه‌ی گره‌ها خواهد بود.



# مرتبه‌ی زمانی (پیچیدگی):
#
# با استفاده از هیپ دودویی (Min-Heap): O((V + E) log V) که V تعداد رأس‌ها و E تعداد یال‌هاست. (این حالت استاندارد و رایج است).
#
# با استفاده از آرایه‌ی ساده (برای گراف‌های متراکم): O(V²).
#
# مرتبه‌ی حافظه (فضای اضافی): O(V) (برای نگهداری آرایه‌ی dist، وضعیت visited، و هیپ).
#
# مهم‌ترین محدودیت (هشدار جدی): اگر حتی یک یال با وزن منفی در گراف وجود داشته باشد، الگوریتم دیکسترا از کار می‌افتد و جواب اشتباه می‌دهد. برای گراف‌های با وزن منفی باید از الگوریتم بلمن-فورد (Bellman-Ford) استفاده کرد.
#
# دلیل درستی (اثبات): چون وزن‌ها نامنفی هستند، زمانی که یک گره از هیپ خارج می‌شود، کوتاه‌ترین مسیر به آن قطعاً پیدا شده است و هیچ مسیر دیگری از طریق گره‌های پردازش‌نشده نمی‌تواند کوتاه‌تر باشد.
#
# کاربردهای واقعی (جایی که حتماً از آن استفاده می‌شود):
