# Special Sorting Algorithms

def shell_sort(arr):
    gap = len(arr)//2

    while gap > 0:
        for i in range(gap, len(arr)):
            temp = arr[i]
            j = i

            while j >= gap and arr[j-gap] > temp:
                arr[j] = arr[j-gap]
                j -= gap

            arr[j] = temp

        gap //= 2

    return arr

print(shell_sort([5, 3, 8, 0, 4, 4, 2]))



# طرز کار Shell Sort
# ایده‌ی اصلی این الگوریتم، بهبود نسخه‌ی ساده‌ی مرتب‌سازی درجی (Insertion Sort) است. می‌دانیم که Insertion Sort وقتی عالی عمل می‌کند که داده‌ها «تقریباً مرتب» باشند. اما اگر کوچکترین عنصر در انتهای آرایه باشد، Insertion Sort مجبور است آن را خانه‌به‌خانه به اول آرایه بیاورد و این خیلی کند است (O(n²)).
#
# Shell Sort این مشکل را با مقایسه و جابه‌جایی عناصری که فاصله‌ی مشخصی (Gap) از هم دارند حل می‌کند. با این کار، عناصر کوچک در چند قدم بزرگ به سمت ابتدا می‌پرند و آرایه سریعاً «نیمه‌مرتب» می‌شود. سپس فاصله را کم می‌کند و دوباره مرتب‌سازی را انجام می‌دهد تا در نهایت به فاصله‌ی ۱ (همان Insertion Sort معمولی) برسد.
#
# به این فرآیند، مرتب‌سازی با فاصله (Diminishing Increment Sort) هم می‌گویند.
#
# مراحل گام‌به‌گام (با دنباله‌ی فاصله‌ی n/2):
#
# یک فاصله‌ی اولیه (Gap) انتخاب می‌کنیم. معمولاً از n/2 شروع می‌کنیم (n تعداد عناصر است).
#
# آرایه را به چند زیرآرایه‌ی مجازی تقسیم می‌کنیم. هر زیرآرایه شامل عناصری است که به اندازه‌ی Gap از هم فاصله دارند (مثلاً عناصر اندیس‌های ۰، Gap، ۲Gap، ...).
#
# روی هر کدام از این زیرآرایه‌ها، یک مرتب‌سازی درجی (Insertion Sort) انجام می‌دهیم.
#
# فاصله را به نصف کاهش می‌دهیم (Gap = Gap / 2).
#
# مراحل ۲ تا ۴ را تکرار می‌کنیم تا زمانی که Gap = 1 شود. در این لحظه، یک Insertion Sort معمولی روی کل آرایه انجام می‌شود، اما چون آرایه از قبل تا حد زیادی مرتب شده، این مرحله‌ی آخر بسیار سریع (نزدیک به O(n)) انجام می‌شود.



# مرتبه‌ی زمانی (پیچیدگی): کاملاً وابسته به دنباله‌ی فاصله (Gap Sequence) است:
#
# دنباله‌ی ساده‌ی n/2: پیچیدگی O(n²) در بدترین حالت.
#
# دنباله‌ی پیشرفته‌تر مثل «دنباله‌ی کات‌هیل (Knuth)» (۳×k + 1) یا «دنباله‌ی سجویک (Sedgewick)»: پیچیدگی به حدود O(n^(3/2)) یا حتی O(n log² n) می‌رسد.
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — کاملاً درجا (In-place) است و هیچ حافظه‌ی اضافی به اندازه‌ی آرایه مصرف نمی‌کند.
#
# آیا پایدار (Stable) است؟ خیر. چون عناصر با فاصله‌های دور جابه‌جا می‌شوند، ترتیب نسبی عناصر مساوی به هم می‌ریزد.
#
# مزیت اصلی: پیاده‌سازی آن بسیار ساده است، حافظه‌ی اضافی نمی‌خواهد، و برای آرایه‌های متوسط (چند هزار عنصر) معمولاً از Insertion Sort ساده خیلی سریع‌تر است و حتی می‌تواند از Heap Sort هم بهتر عمل کند. به همین دلیل در برخی سیستم‌های تعبیه‌شده (Embedded Systems) که حافظه محدود است، گزینه‌ی مناسبی محسوب می‌شود.
#
# معایب اصلی: دنباله‌ی فاصله‌ی مناسب برای همه‌ی حالات به‌سختی پیدا می‌شود، و برای آرایه‌های خیلی بزرگ، عملکردش از الگوریتم‌هایی مثل Quick Sort و IntroSort پایین‌تر است. همچنین ناپایدار بودن، آن را برای داده‌های حساس به ترتیب نامناسب می‌کند.

