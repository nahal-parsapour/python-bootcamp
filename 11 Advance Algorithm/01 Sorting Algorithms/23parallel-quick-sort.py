from concurrent.futures import ThreadPoolExecutor
import random

def parallel_quick_sort(arr, depth=0, max_depth=2):
    if len(arr) <= 1:
        return arr

    pivot = random.choice(arr)
    left  = [x for x in arr if x < pivot]
    mid   = [x for x in arr if x == pivot]
    right = [x for x in arr if x > pivot]

    if depth < max_depth:
        with ThreadPoolExecutor(max_workers=2) as ex:
            left_sorted, right_sorted = list(ex.map(
                lambda x: parallel_quick_sort(x, depth+1, max_depth),
                [left, right]
            ))
    else:
        left_sorted = parallel_quick_sort(left, depth+1, max_depth)
        right_sorted = parallel_quick_sort(right, depth+1, max_depth)

    return left_sorted + mid + right_sorted

arr = [5,3,8,4,2,9,1,7]
print(parallel_quick_sort(arr))



# تفاوت اصلی با Quick Sort معمولی
# در Quick Sort معمولی، مراحل انتخاب محور (Pivot)، بازچینی (Partition) و فراخوانی‌های بازگشتی، همگی به‌صورت ترتیبی (Sequential) انجام می‌شوند. یعنی ابتدا کل آرایه بازچینی می‌شود، سپس نیمه‌ی چپ مرتب می‌شود، و بعد از آن نوبت به نیمه‌ی راست می‌رسد.
#
# در Parallel Quick Sort، از چندین هسته‌ی پردازنده برای انجام همزمان کارها استفاده می‌کنیم. بزرگترین چالش این الگوریتم، موازی‌سازی مرحله‌ی بازچینی (Partitioning) است؛ چون برخلاف Merge Sort که ادغام (Merge) کار ساده‌ای است، در Quick Sort باید عناصر را حول یک محور جابه‌جا کنیم و این کار به‌صورت ذاتی وابسته به ترتیب است.
#
# برای حل این مشکل، دو رویکرد اصلی وجود دارد که در عمل از ترکیب هر دو استفاده می‌شود.
#
# طرز کار Parallel Quick Sort
# رویکرد اول (ساده‌ترین و رایج‌ترین در عمل): بازچینی ترتیبی + بازگشت موازی
#
# در این روش، فقط مرحله‌ی بازگشت (Recursion) را موازی می‌کنیم و مرحله‌ی بازچینی را همچنان با یک هسته انجام می‌دهیم:
#
# یک هسته، محور (Pivot) را انتخاب کرده و کل آرایه را بازچینی (Partition) می‌کند (این مرحله ترتیبی است و گلوگاه محسوب می‌شود).
#
# پس از مشخص شدن جای نهایی محور، آرایه به دو زیرآرایه‌ی چپ و راست تقسیم می‌شود.
#
# نقطه‌ی کلیدی: به جای اینکه اول چپ و بعد راست را مرتب کنیم، دو هسته‌ی مجزا (یا دو ریسه) را همزمان برای مرتب‌سازی این دو زیرآرایه راه‌اندازی می‌کنیم.
#
# این کار را به‌صورت بازگشتی ادامه می‌دهیم تا به آرایه‌های کوچک برسیم. برای آرایه‌های کوچک‌تر از یک آستانه (مثلاً ۵۰۰۰ عنصر)، دیگر ریسه‌ی جدید نمی‌سازیم و با Quick Sort ترتیبی یا Insertion Sort کار را تمام می‌کنیم تا سربار ایجاد ریسه کاهش یابد.
#
# رویکرد دوم (پیشرفته و واقعاً موازی): بازچینی موازی با استفاده از «جمع پیشوندی» (Parallel Partitioning using Prefix Sum)
#
# این روش برای آرایه‌های بسیار بزرگ (میلیاردها عنصر) استفاده می‌شود تا گلوگاه بازچینی ترتیبی را نیز برطرف کند:
#
# انتخاب محور: یک هسته، محور را انتخاب می‌کند (معمولاً به‌صورت تصادفی یا میانه‌ی سه‌تایی).
#
# تقسیم کار: آرایه را به P بخش مساوی (تعداد هسته‌ها) تقسیم می‌کنیم. هر هسته، بخش خود را اسکن می‌کند و دو کار انجام می‌دهد:
#
# تعداد عناصر کوچک‌تر از محور را در بخش خود می‌شمارد.
#
# عناصر کوچک‌تر و بزرگ‌تر از محور را در دو آرایه‌ی موقت محلی جداگانه ذخیره می‌کند.
#
# محاسبه‌ی جایگاه‌ها (Prefix Sum / Scan): با استفاده از یک عملیات جمع پیشوندی موازی (Parallel Prefix Sum)، مشخص می‌کنیم که هر بخش از عناصر کوچک‌تر، دقیقاً در چه اندیسی از آرایه‌ی نهایی باید قرار بگیرند. مثلاً اگر بخش اول ۱۰۰ عنصر کوچک‌تر داشت و بخش دوم ۱۵۰ عنصر، می‌دانیم که عناصر بخش دوم باید از اندیس ۱۰۰ شروع شوند.
#
# قراردهی نهایی (Parallel Placement): هر هسته، عناصر کوچک‌تر و بزرگ‌تر خود را با استفاده از اندیس‌های محاسبه‌شده، مستقیماً در آرایه‌ی کمکی در جای درست قرار می‌دهد (این کار کاملاً موازی و بدون تداخل انجام می‌شود).
#
# جایگذاری محور: محور را درست بین دو بخش (جایی که عناصر کوچک‌تر تمام می‌شوند) قرار می‌دهیم.
#
# در نهایت، آرایه‌ی کمکی را دوباره در آرایه‌ی اصلی کپی می‌کنیم (یا اگر حافظه اجازه دهد، با همان ادامه می‌دهیم). حالا آرایه به‌طور کامل حول محور بازچینی شده است و دو زیرآرایه‌ی چپ و راست مستقل ایجاد شده‌اند. سپس همین فرایند را به‌صورت موازی روی هر دو زیرآرایه تکرار می‌کنیم.




# مرتبه‌ی زمانی (پیچیدگی):
#
# رویکرد بازچینی ترتیبی + بازگشت موازی: O(n log n / P) در حالت متوسط، اما مرحله‌ی بازچینی همچنان O(n) ترتیبی است، بنابراین در عمل برای تعداد هسته‌های زیاد، به O(n + (n/P) log n) محدود می‌شود.
#
# رویکرد بازچینی موازی (با Prefix Sum): در حالت ایده‌آل، زمان به O((n/P) log n) کاهش می‌یابد.
#
# بدترین حالت (انتخاب محور بد): همچنان ممکن است به O(n²) برسد، اما با انتخاب محور تصادفی یا میانه‌ی سه‌تایی، این احتمال در موازی‌سازی به شدت کاهش می‌یابد.
#
# مرتبه‌ی حافظه (فضای اضافی):
#
# در رویکرد بازگشت موازی (بدون بازچینی موازی): O(log n) برای پشته‌ی بازگشت (مانند حالت ترتیبی).
#
# در رویکرد بازچینی موازی با Prefix Sum: O(n) حافظه‌ی اضافی برای آرایه‌ی کمکی نیاز دارد (مشابه Merge Sort).
#
# آیا پایدار (Stable) است؟ خیر. چون عناصر با جابه‌جایی (Swap) در حین بازچینی، ترتیب خود را از دست می‌دهند و در نسخه‌ی موازی نیز این ویژگی حفظ نمی‌شود.
#
# نکته‌ی پیاده‌سازی (آستانه): در هر دو رویکرد، اگر اندازه‌ی زیرآرایه از یک عدد مشخص (مثلاً ۵۰۰۰) کمتر شد، دیگر ریسه‌ی جدید ایجاد نمی‌کنیم و از مرتب‌سازی درجی (Insertion Sort) یا Quick Sort ترتیبی استفاده می‌کنیم تا سربار سنگین ایجاد و همگام‌سازی ریسه‌ها را حذف کنیم.
#
# مزیت اصلی: Quick Sort در حالت عادی (تک‌هسته‌ای) از Merge Sort سریع‌تر است (به خاطر استفاده‌ی بهتر از کش پردازنده). در نسخه‌ی موازی نیز همین مزیت حفظ می‌شود و در عمل، Parallel Quick Sort اغلب از Parallel Merge Sort برای داده‌های تصادفی سریع‌تر اجرا می‌شود، به شرطی که بازچینی به‌خوبی موازی شده باشد.
#
# معایب اصلی (چالش‌ها):
#
# پیاده‌سازی بازچینی موازی با Prefix Sum بسیار پیچیده است و نیاز به عملیات همگام‌سازی (Synchronization) در مرحله‌ی جمع پیشوندی دارد.
#
# بدترین حالت O(n²) اگرچه نادر است، اما در سیستم‌های بلادرنگ (Real-time) ریسک محسوب می‌شود.
#
# در رویکرد «بازچینی ترتیبی + بازگشت موازی»، با افزایش تعداد هسته‌ها، گلوگاه مرحله‌ی بازچینی ترتیبی بیشتر نمایان می‌شود و افزایش سرعت متوقف می‌شود (مشکل مقیاس‌پذیری).
#
# کاربرد واقعی: در کتابخانه‌ی Parallel STL در C++ (مثل std::sort(std::execution::par, ...)) و چارچوب‌های پردازش موازی مانند Java Fork/Join، از نسخه‌ی بهینه‌شده‌ی همین الگوریتم (اغلب با بازچینی ترتیبی و بازگشت موازی) برای مرتب‌سازی آرایه‌های بزرگ استفاده می‌شود.