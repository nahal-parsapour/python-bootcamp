graph = {
    1: [2],
    2: [3],
    3: [4],
    4: [2]
}

def find_first_cycle(graph):
    visited = set()
    stack = []

    def dfs(u):
        visited.add(u)
        stack.append(u)
        for v in graph.get(u, []):
            if v not in visited:
                res = dfs(v)
                if res:
                    return res
            elif v in stack:
                idx = stack.index(v)
                return stack[idx:] + [v]
        stack.pop()
        return None

    for node in graph:
        if node not in visited:
            cycle = dfs(node)
            if cycle:
                return cycle
    return None

cycle = find_first_cycle(graph)
print("Cycle found:", " → ".join(map(str, cycle)))



def find_all_cycles(graph):
    cycles = set()
    path = []

    def dfs(u):
        path.append(u)
        for v in graph.get(u, []):
            if v in path:
                idx = path.index(v)
                cyc = tuple(path[idx:] + [v])
                cycles.add(cyc)
            else:
                dfs(v)
        path.pop()

    for node in graph:
        dfs(node)
    return cycles

for cyc in find_all_cycles(graph):
    print("Cycle:", " → ".join(map(str, cyc)))





# طرز کار DFS
# ایده‌ی اصلی این الگوریتم، تا آنجا که ممکن است در یک مسیر جلو برو، و وقتی به بن‌بست رسیدی، به عقب برگرد (Backtrack) و مسیر دیگر را امتحان کن.
# این دقیقاً شبیه به حرکت در یک هزارتو است: دیوار را با دست چپ لمس می‌کنید و تا انتهای راهرو می‌روید، وقتی به دیوار بن‌بست رسیدید، برمی‌گردید به آخرین چهارراه و مسیر بعدی را می‌روید.
#
# در گراف، این الگوریتم از یک پشته (Stack) استفاده می‌کند (به‌صورت صریح با ساختمان داده، یا به‌صورت ضمنی با فراخوانی‌های بازگشتی (Recursion)). قانون آن این است: همیشه عمیق‌ترین گره‌ی ملاقات‌نشده را اول پردازش کن.
#
# مراحل گام‌به‌گام (روش بازگشتی - رایج‌ترین)
# ۱. یک مجموعه (یا آرایه) برای مشخص‌کردن گره‌های ملاقات‌شده (Visited) نگهداری می‌کنیم.
# ۲. از گره‌ی شروع (Start Node) شروع می‌کنیم.
# ۳. آن را به‌عنوان ملاقات‌شده علامت‌گذاری کرده و پردازشش می‌کنیم (مثلاً چاپ می‌کنیم).
# ۴. به‌صورت بازگشتی، این کار را برای هر کدام از همسایه‌هایی که تا کنون ملاقات نشده‌اند انجام می‌دهیم.
# ۵. وقتی هیچ همسایه‌ی ملاقات‌نشده‌ای باقی نماند، تابع بازگشتی تمام می‌شود و به عقب برمی‌گردد (Backtrack) تا گره‌ی قبلی، همسایه‌ی بعدی خود را امتحان کند.
#
# مراحل گام‌به‌گام (روش پشته‌ای صریح - Iterative):
#
# ۱. گره‌ی شروع را در پشته (Stack) قرار دهید و ملاقات‌شده علامت بزنید.
# ۲. تا زمانی که پشته خالی نشده است:
#
# یک گره را از بالای پشته خارج کنید (Pop). این گره‌ی جاری شماست.
#
# گره‌ی جاری را پردازش کنید.
#
# همه‌ی همسایه‌های ملاقات‌نشده‌ی آن را به بالای پشته اضافه کنید (Push) و آن‌ها را ملاقات‌شده علامت بزنید.
# (نکته: ترتیب پیمایش به ترتیبی که همسایه‌ها به پشته اضافه می‌شوند بستگی دارد).



# مرتبه‌ی زمانی (پیچیدگی): O(V + E) که V تعداد رأس‌ها و E تعداد یال‌ها است. دقیقاً مثل BFS، چون هر رأس و هر یال دقیقاً یک بار بررسی می‌شوند.
#
# مرتبه‌ی حافظه (فضای اضافی):
#
# در روش بازگشتی: O(V) برای پشته‌ی فراخوانی (Call Stack) در بدترین حالت (مثلاً یک گراف خطی).
#
# در روش پشته‌ای صریح: O(V) برای پشته.
#
# به علاوه O(V) برای آرایه‌ی Visited.
#
# مقایسه با BFS (جستجوی سطح‌اول):
#
# BFS از صف (Queue) استفاده می‌کند و لایه‌به‌لایه جلو می‌رود. کوتاه‌ترین مسیر را در گراف‌های بدون وزن پیدا می‌کند.
#
# DFS از پشته (Stack) استفاده می‌کند و تا عمق ممکن پیش می‌رود. کوتاه‌ترین مسیر را تضمین نمی‌کند، اما برای تشخیص دور (Cycle Detection)، مرتب‌سازی توپولوژیک (Topological Sort)، و حل مسائل پازل (مثل N-Queens یا سودوکو) بسیار عالی است.
#
# مزیت اصلی نسبت به BFS: حافظه‌ی کمتری در گراف‌های پهن (با تعداد فرزندان زیاد) مصرف می‌کند، چون فقط مسیر فعلی را در پشته نگه می‌دارد، نه کل یک سطح را.
#
# معایب اصلی: اگر گراف خیلی عمیق باشد (مثلاً ۱۰۰ هزار گره پشت سر هم)، پشته‌ی بازگشتی ممکن است دچار سرریز پشته (Stack Overflow) شود. در این موارد باید از نسخه‌ی پشته‌ی صریح (Iterative) استفاده کرد. همچنین پیدا کردن کوتاه‌ترین مسیر با DFS بدون تغییرات اضافی ممکن نیست.
#
# کاربردهای واقعی:
#
# خزیدن وب (Web Crawling) برای ایندکس کردن صفحات (نسخه‌های اولیه).
#
# پیدا کردن مؤلفه‌های همبند (Connected Components) در شبکه‌های اجتماعی.
#
# حل معماهای منطقی (مثل مسیر‌یابی در بازی‌ها).
#
# پیاده‌سازی کامپایلرها (پیمایش درخت نحو انتزاعی - AST).
#
# الگوریتم‌های پیشرفته‌تر مثل یافتن مؤلفه‌های همبند قوی (SCC با الگوریتم تارجان) که هسته‌ی اصلی آن DFS است.

