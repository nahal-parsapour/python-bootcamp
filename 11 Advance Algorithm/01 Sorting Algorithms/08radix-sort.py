def counting_sort_exp(arr, exp):
    output = [0]*len(arr)
    count = [0]*10

    for num in arr:
        index = num // exp
        count[index % 10] += 1

    for i in range(1, 10):
        count[i] += count[i-1]

    for num in reversed(arr):
        index = num // exp
        output[count[index % 10] - 1] = num
        count[index % 10] -= 1

    return output

def radix_sort(arr):
    mx = max(arr)
    exp = 1
    while mx // exp > 0:
        arr = counting_sort_exp(arr, exp)
        exp *= 10
    return arr

print(radix_sort([5, 3, 8, 0, 4, 4, 2]))




# طرز کار Radix Sort
# ایده‌ی اصلی این الگوریتم این است که به جای مقایسه‌ی کل اعداد با هم، ارقام آن‌ها را یکی‌یکی مرتب می‌کند. رادیکس سورت یک الگوریتم غیر‑مقایسه‌ای است و بر پایه‌ی مرتب‌سازی شمارشی (Counting Sort) یا مرتب‌سازی سطلی (Bucket Sort) به عنوان زیرروال اجرا می‌شود.
#
# دو روش اصلی برای اجرای آن وجود دارد که معروف‌ترین و رایج‌ترین آن، LSD (کم‌ارزش‌ترین رقم - Least Significant Digit) است که از رقم یکان به سمت چپ (رقم‌های بزرگ‌تر) حرکت می‌کند.
#
# مراحل گام‌به‌گام (روش LSD):
#
# بزرگترین عدد آرایه را پیدا کنید تا تعداد ارقام (تعداد تکرار) مشخص شود.
#
# یک متغیر place = 1 (نمایانگر رقم یکان) در نظر بگیرید.
#
# تا زمانی که به تعداد ارقام بزرگترین عدد نرسیده‌اید، مرحله‌ی ۴ را تکرار کنید.
#
# مرحله‌ی کلیدی: تمام اعداد آرایه را بر اساس رقم موجود در جایگاه place (مثلاً یکان، دهگان، صدگان و ...) مرتب کنید. این مرتب‌سازی باید پایدار (Stable) باشد (معمولاً با Counting Sort پیاده‌سازی می‌شود، چون اعداد بین ۰ تا ۹ هستند).
#
# place را در ۱۰ ضرب کنید (بروید به رقم بعدی) و مرحله‌ی ۴ را دوباره اجرا کنید.
#
# وقتی همه‌ی ارقام پردازش شدند، آرایه کاملاً مرتب است.


# مرتبه‌ی زمانی (پیچیدگی): O(d × (n + b)) که در آن:
# d = تعداد ارقام بزرگترین عدد (تعداد پاس‌ها).
# n = تعداد عناصر آرایه.
# b = پایه‌ی عددی (مثلاً برای اعداد ده‌دهی، b = 10).
# اگر d عدد ثابتی باشد (مثلاً اعداد ۳۲‌بیتی همیشه ۱۰ رقم دارند)، عملاً پیچیدگی به O(n) تبدیل می‌شود که بسیار سریع است.
#
# مرتبه‌ی حافظه (فضای اضافی): O(n + b) — معمولاً برای پیاده‌سازی Counting Sort در هر پاس، به حافظه‌ی کمکی نیاز دارد.
#
# آیا پایدار (Stable) است؟ بله، به شرطی که زیرالگوریتم مورد استفاده (مثلاً Counting Sort) پایدار باشد. این ویژگی برای Radix Sort حیاتی است، زیرا پایداری باعث می‌شود ترتیب حاصل از پاس‌های قبلی در پاس‌های بعدی به هم نخورد.
#
# چه زمانی عالی عمل می‌کند؟ زمانی که می‌خواهید اعداد صحیح با طول ثابت (مثلاً کدهای ملی، شماره تلفن، آی‌پی‌ها، یا اعداد ۳۲‌بیتی و ۶۴‌بیتی) را مرتب کنید. از تمام الگوریتم‌های مقایسه‌ای مثل Quick Sort در این موارد سریع‌تر است.
#
# محدودیت‌های اصلی:
#
# فقط برای داده‌های قابل نمایش با ارقام (اعداد صحیح یا رشته‌های با طول ثابت) کار می‌کند. برای اعداد اعشاری به‌سادگی قابل استفاده نیست (مگر با تغییر مبنا).
#
# اگر دامنه‌ی ارقام (مثلاً b) خیلی بزرگ باشد (مثلاً ۲۵۶ برای بایت‌ها) یا تعداد ارقام (d) خیلی زیاد باشد، کارایی آن کاهش می‌یابد.
#
# برخلاف Quick Sort که روی کش پردازنده عالی عمل می‌کند، Radix Sort به حافظه‌ی پرشی (غیرهمجوار) دسترسی دارد و ممکن است در عمل برای آرایه‌های خیلی بزرگ با تعداد ارقام زیاد، کندتر از Quick Sort باشد.
