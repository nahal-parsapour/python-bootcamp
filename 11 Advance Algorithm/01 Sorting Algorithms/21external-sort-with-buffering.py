# فرض: هر بار فقط می‌تونی مثلاً ۱۰۰۰ عدد رو تو RAM نگه داری (به‌جای ۱MB واقعی).

def external_sort_with_buffer(data, buffer_size=1000):
    chunks = []
    for i in range(0, len(data), buffer_size):
        chunk = data[i:i + buffer_size]
        chunk.sort()
        chunks.append(chunk)
        print(f"Sorted chunk {len(chunks)-1}: {chunk[:10]} ...")

    indices = [0] * len(chunks)
    result = []

    while True:
        min_val = None
        min_idx = -1
        for i, chunk in enumerate(chunks):
            if indices[i] < len(chunk):
                val = chunk[indices[i]]
                if min_val is None or val < min_val:
                    min_val = val
                    min_idx = i
        if min_idx == -1:
            break
        result.append(min_val)
        indices[min_idx] += 1

    print("Final sorted (first 20):", result[:20])
    return result

data = [9,1,5,3,8,2,7,4,6]
external_sort_with_buffer(data, buffer_size=3)




# طرز کار External Sort with Buffering
# این الگوریتم همان دو فاز اصلی External Merge Sort را دارد، اما با یک تفاوت حیاتی در نحوه‌ی مدیریت حافظه در فاز دوم (ادغام).
#
# فاز اول: ایجاد اجراهای مرتب (بدون تغییر خاصی)
# داده را به تکه‌های کوچک تقسیم کرده، هر تکه را در RAM مرتب کرده و به عنوان یک «اجرا» (Run) روی دیسک ذخیره می‌کنیم.
#
# فاز دوم: ادغام چندراهه با بافر (Multi-way Merge with Buffering)
# حافظه‌ی RAM موجود را به B + 1 بخش مجزا (بافر) تقسیم می‌کنیم:
#
# B بافر ورودی (Input Buffers): به ازای هر اجرایی که قرار است همزمان ادغام کنیم، یک بافر به اندازه‌ی یک بلوک دیسک در نظر می‌گیریم.
#
# ۱ بافر خروجی (Output Buffer): یک بافر برای ذخیره‌ی موقت نتیجه‌ی ادغام قبل از نوشتن روی دیسک.
#
# مراحل گام‌به‌گام در یک دور ادغام:
#
# پر کردن اولیه (Initial Fill): از هر یک از B اجرا، اولین بلوک را خوانده و در بافر ورودی مخصوص آن قرار می‌دهیم.
#
# انتخاب و خروجی (Selection & Output): کوچکترین رکورد را بین تمام بافرهای ورودی (با استفاده از یک هیپ) پیدا می‌کنیم. آن را برمی‌داریم و در بافر خروجی می‌نویسیم.
#
# شارژ مجدد بافر ورودی (Refill): اگر بافر یک اجرا کاملاً خالی شد (همه‌ی رکوردهای آن بلوک مصرف شدند)، بلوک بعدی همان اجرا را از دیسک می‌خوانیم و بافر را پر می‌کنیم. (توجه کنید که این خواندن، یک خواندن ترتیبی از دیسک است، نه تصادفی، چون بلوک‌های هر اجرا پشت سر هم قرار دارند).
#
# تخلیه‌ی بافر خروجی (Flush): اگر بافر خروجی پر شد، کل آن را یک‌باره روی دیسک (در فایل خروجی موقت) می‌نویسیم. این یک نوشتن ترتیبی است که بسیار سریع است.
#
# این کار را تا وقتی ادامه می‌دهیم که همه‌ی رکوردهای همه‌ی اجراها مصرف شوند. در پایان، اگر بافر خروجی هنوز کاملاً پر نشده ولی رکوردی باقی نمانده، آن را هم روی دیسک می‌نویسیم (Flush نهایی).



# نکته‌ی فنی مهم: تعداد بافرها در مقابل اندازه‌ی بافرها
# یک معامله‌ی کلیدی (Trade-off) در این الگوریتم وجود دارد:
#
# اگر تعداد بافرهای ورودی (B) را زیاد کنیم، درجه‌ی ادغام بالاتر می‌رود و تعداد پاس‌های ادغام کاهش می‌یابد (به log_B(تعداد اجراها) می‌رسد).
#
# اما اگر B را زیاد کنیم، با حافظه‌ی ثابت، اندازه‌ی هر بافر کوچک‌تر می‌شود. بافرهای کوچک یعنی باید بیشتر به دیسک مراجعه کنیم تا بلوک‌ها را بخوانیم.
#
# بنابراین، مهندسان نرم‌افزار باید تعادل را رعایت کنند تا مجموع زمان I/O کمینه شود.




# معیار اصلی کارایی (I/O Complexity): تعداد بلوک‌های خوانده/نوشته شده از دیسک. اگر مجموع داده N بلوک باشد و حافظه M بلوک گنجایش داشته باشد، تعداد پاس‌های ادغام log_M(N) و تعداد کل I/Oها از مرتبه‌ی O(N log_M(N)) است که نسبت به حالت بدون بافر که O(N * تعداد رکوردها) بود، یک پیشرفت عظیم محسوب می‌شود.
#
# مرتبه‌ی حافظه (RAM): O(M) که M اندازه‌ی کل حافظه‌ی در نظر گرفته‌شده برای بافرهاست. معمولاً این مقدار را تا ۸۰٪ حافظه‌ی خالی سیستم بالا می‌برند تا کارایی بیشینه شود.
#
# آیا پایدار (Stable) است؟ بله، به شرطی که در هنگام برابری رکوردها در مرحله‌ی ادغام، اولویت را به اجرای قبلی دهیم.
#
# مزیت اصلی (دلیل وجودش): دیسک‌های سخت (و حتی SSDها) وقتی داده را به‌صورت ترتیبی (پشت سر هم) می‌خوانند، ده‌ها برابر سریع‌تر از حالت تصادفی عمل می‌کنند. بافرینگ دقیقاً کاری می‌کند که تمام دسترسی‌های به دیسک به حالت ترتیبی تبدیل شوند. به همین دلیل، همه‌ی پایگاه‌های داده‌ی مدرن (مثل PostgreSQL، Oracle، MySQL) و سیستم‌های فایل برای مرتب‌سازی داده‌های حجیم، از این تکنیک استفاده می‌کنند.
#
# معایب اصلی: مدیریت حافظه (تقسیم بافرها، تخصیص و آزادسازی) به مراتب پیچیده‌تر از الگوریتم‌های ساده است. همچنین اگر اندازه‌ی یک بلوک را اشتباه انتخاب کنید (خیلی کوچک یا خیلی بزرگ)، کارایی به شدت کاهش می‌یابد. علاوه بر این، اگر کلیدهای مرتب‌سازی بسیار کوچک باشند، سربار (Overhead) نگهداری هیپ و بافرها ممکن است از مزایای آن بکاهد (البته در داده‌های بزرگ، این سربار ناچیز است).