def odd_even_sort(arr):
    n = len(arr)
    sorted_flag = False
    iterations = 0

    while not sorted_flag:
        sorted_flag = True
        iterations += 1
        print(f"Iteration {iterations}:")

        # فاز odd
        print("  Odd phase:")
        for i in range(1, n - 1, 2):
            print(f"    Compare {arr[i]} and {arr[i+1]}")
            if arr[i] > arr[i + 1]:
                arr[i], arr[i + 1] = arr[i + 1], arr[i]
                sorted_flag = False

        # فاز even
        print("  Even phase:")
        for i in range(0, n - 1, 2):
            print(f"    Compare {arr[i]} and {arr[i+1]}")
            if arr[i] > arr[i + 1]:
                arr[i], arr[i + 1] = arr[i + 1], arr[i]
                sorted_flag = False

        print("  Array:", arr)

    print("Total iterations:", iterations)
    return arr, iterations


arr = [5, 3, 8, 0, 4, 4, 2]
odd_even_sort(arr)





# طرز کار Odd-Even Sort
# ایده‌ی اصلی این الگوریتم، بسیار شبیه به مرتب‌سازی حبابی (Bubble Sort) است، اما با یک تفاوت کلیدی: به جای اینکه فقط از چپ به راست برویم، عناصر را در دو فاز مجزا مقایسه و جابه‌جا می‌کنیم. به همین دلیل، این الگوریتم برای اجرا روی پردازنده‌های موازی (چند هسته‌ای) بسیار عالی است، چون در هر فاز، همه‌ی مقایسه‌ها مستقل از هم هستند و می‌توانند همزمان انجام شوند.
#
# الگوریتم دو فاز اصلی دارد که مرتباً تکرار می‌شوند تا آرایه کاملاً مرتب شود:
#
# فاز اول (فاز فرد - Odd Phase):
# تمام جفت‌های با اندیس فرد (یعنی جفت‌های (1,2)، (3,4)، (5,6) و ...) را با هم مقایسه می‌کند. اگر عنصر چپ از عنصر راست بزرگ‌تر بود، آن‌ها را جابه‌جا (Swap) می‌کند.
#
# فاز دوم (فاز زوج - Even Phase):
# تمام جفت‌های با اندیس زوج (یعنی جفت‌های (0,1)، (2,3)، (4,5) و ...) را با هم مقایسه می‌کند. اگر عنصر چپ از عنصر راست بزرگ‌تر بود، آن‌ها را جابه‌جا می‌کند.
#
# الگوریتم این دو فاز را آنقدر تکرار می‌کند تا در یک فاز کامل (هم فرد و هم زوج) هیچ جابه‌جایی انجام نشود؛ یعنی آرایه مرتب شده است.


# مرتبه‌ی زمانی (پیچیدگی): در بهترین، متوسط و بدترین حالت، همگی O(n²) هستند. (اگر بهینه‌سازی «پرچم جابه‌جایی» را اضافه کنید، در بهترین حالت (آرایه مرتب) یک پاس کامل O(n) زمان می‌برد، اما در حالت کلی همچنان O(n²) محسوب می‌شود).
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — کاملاً درجا (In-place) است و فقط با یک متغیر موقت جابه‌جایی انجام می‌دهد.
#
# آیا پایدار (Stable) است؟ بله. اگر دو عدد مساوی داشته باشیم، شرط جابه‌جایی فقط برای «بزرگ‌تر» است، پس آن‌ها را جابه‌جا نمی‌کند و ترتیب نسبی عناصر مساوی حفظ می‌شود.
#
# مزیت اصلی: سادگی فوق‌العاده و قابلیت موازی‌سازی بالا. برای نمایش الگوریتم‌های موازی در درس‌های دانشگاهی بسیار استفاده می‌شود.
#
