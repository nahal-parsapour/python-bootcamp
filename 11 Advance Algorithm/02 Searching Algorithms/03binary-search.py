# طرز کار Binary Search
# ایده‌ی اصلی این الگوریتم، «تقسیم و غلبه» (Divide and Conquer) است. به جای اینکه مثل جستجوی خطی یکی‌یکی جلو برویم، در هر مرحله فضای جستجو را به نصف کاهش می‌دهیم. اما این کار فقط در صورتی ممکن است که آرایه از قبل مرتب باشد (صعودی یا نزولی).
#
# الگوریتم با سه اشاره‌گر (اندیس) کار می‌کند:
#
# low: ابتدای بازه‌ی جستجو.
#
# high: انتهای بازه‌ی جستجو.
#
# mid: وسط بازه‌ی جستجو (محاسبه می‌شود: mid = (low + high) / 2).
#
# مراحل گام‌به‌گام (برای آرایه‌ی صعودی):
#
# low = 0 و high = n-1 (طول آرایه منهای یک) را تنظیم کنید.
#
# تا وقتی که low از high بزرگتر نشده است، مرحله‌ی ۳ را تکرار کنید.
#
# mid را محاسبه کنید.
#
# مقدار arr[mid] را با مقدار مورد جستجو (target) مقایسه کنید:
#
# اگر arr[mid] == target → جستجو موفق بود. اندیس mid را برگردانید.
#
# اگر target < arr[mid] → یعنی هدف در نیمه‌ی چپ قرار دارد. پس high = mid - 1 کنید (بازه را به چپ ببرید).
#
# اگر target > arr[mid] → یعنی هدف در نیمه‌ی راست قرار دارد. پس low = mid + 1 کنید (بازه را به راست ببرید).
#
# اگر حلقه تمام شد و هنوز هدف را پیدا نکرده‌اید، یعنی عنصر در آرایه وجود ندارد. مقدار -1 (یا یک مقدار از پیش تعیین‌شده) را برگردانید.




# مرتبه‌ی زمانی (پیچیدگی): در بهترین، متوسط و بدترین حالت، همگی O(log n) هستند. (چون در هر مرحله، فضای جستجو نصف می‌شود. مثلاً برای ۱ میلیارد عنصر، فقط به حدود ۳۰ مرحله نیاز دارد!).
#
# مرتبه‌ی حافظه (فضای اضافی):
#
# پیاده‌سازی تکراری (Iterative): O(1) — هیچ حافظه‌ی اضافی مصرف نمی‌کند.
#
# پیاده‌سازی بازگشتی (Recursive): O(log n) — به خاطر پشته‌ی فراخوانی (Call Stack).
#
# پیش‌نیاز اصلی: آرایه باید مرتب شده باشد. اگر مرتب نباشد، جستجوی دودویی کار نمی‌کند و جواب اشتباه می‌دهد.
#
# آیا می‌توان روی لیست پیوندی (Linked List) اجرا کرد؟ به‌سختی و بسیار ناکارآمد. چون لیست پیوندی دسترسی تصادفی با اندیس (Random Access) را پشتیبانی نمی‌کند و برای رفتن به mid باید یکی‌یکی پیمایش کرد که عملاً آن را به O(n) تبدیل می‌کند.
#
# مزیت اصلی: فوق‌العاده سریع برای داده‌های بزرگ. اگر یک بار هزینه‌ی مرتب‌سازی را بپردازید، می‌توانید میلیون‌ها بار جستجوی دودویی را با سرعت بسیار بالا انجام دهید.
#
# معایب اصلی: نیاز به آرایه‌ی مرتب دارد. اگر داده‌ها مدام در حال اضافه یا حذف شدن باشند، هزینه‌ی حفظ مرتب‌بودن می‌تواند بسیار بالا باشد (در آن موارد باید از ساختمان‌های داده‌ی دیگری مثل درخت‌های جستجوی دودویی استفاده کرد). همچنین پیاده‌سازی دقیق آن نیازمند دقت در محاسبه‌ی mid برای جلوگیری از سرریز (Overflow) در زبان‌های سطح پایین است (معمولاً از mid = low + (high - low) / 2 استفاده می‌کنند).