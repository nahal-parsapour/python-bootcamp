def gnome_sort(arr):
    index = 0
    swaps = 0

    while index < len(arr):
        if index == 0 or arr[index] >= arr[index - 1]:
            index += 1
        else:
            arr[index], arr[index - 1] = arr[index - 1], arr[index]
            swaps += 1
            index -= 1

    print("Final array:", arr)
    print("Total swaps:", swaps)
    return arr, swaps

arr = [5, 3, 8, 0, 4, 2]
gnome_sort(arr)




# طرز کار Gnome Sort
# ایده‌ی اصلی این الگوریتم، بسیار ساده و شبیه به مرتب‌سازی درجی (Insertion Sort) است، اما به جای شیفت دادن عناصر، از جابه‌جایی (Swap) استفاده می‌کند.
#
# الگوریتم با یک اشاره‌گر (اندیس) از ابتدای آرایه شروع می‌کند و طبق قانون زیر حرکت می‌کند:
#
# اگر در ابتدای آرایه هستید (index == 0)، یک قدم به جلو بروید.
#
# اگر عنصر جاری بزرگ‌تر یا مساوی عنصر قبلی است (یعنی ترتیبشان درست است)، یک قدم به جلو بروید.
#
# اگر عنصر جاری کوچک‌تر از عنصر قبلی است (ترتیب اشتباه است)، آن دو را جابه‌جا کنید و یک قدم به عقب برگردید (تا دوباره ترتیب عناصر قبلی را بررسی کنید).
#
# این کار را آنقدر تکرار می‌کند تا به انتهای آرایه برسد. در واقع، این الگوریتم یک حلقه‌ی تکی (while) است که با عقب و جلو رفتن، به‌تدریج عناصر کوچک را به سمت ابتدا می‌آورد.



# مرتبه‌ی زمانی (پیچیدگی):
#
# بهترین حالت (آرایه از قبل مرتب): O(n) — فقط یک بار از ابتدا تا انتها می‌رود و هیچ جابه‌جایی انجام نمی‌دهد.
#
# حالت متوسط و بدترین حالت (آرایه نزولی): O(n²) — چون عناصر کوچک را یکی‌یکی به عقب می‌آورد.
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — کاملاً درجا (In-place) است و هیچ حافظه‌ی اضافی مصرف نمی‌کند.
#
# آیا پایدار (Stable) است؟ بله. شرط جابه‌جایی فقط برای کوچک‌تر (<) است، بنابراین عناصر مساوی جابه‌جا نمی‌شوند و ترتیب نسبی آن‌ها حفظ می‌شود.
#
# مقایسه با Insertion Sort: گنوم سورت دقیقاً همان کاری را انجام می‌دهد که Insertion Sort انجام می‌دهد، با این تفاوت که به جای «شیفت دادن» (Shift) عناصر برای جا باز کردن، از «جابه‌جایی» (Swap) استفاده می‌کند. به همین دلیل، کد آن بسیار ساده‌تر و کوتاه‌تر است، اما در عمل به خاطر جابه‌جایی‌های زیاد، کمی کندتر از Insertion Sort اجرا می‌شود.
#
# معایب اصلی: کاملاً جنبه‌ی آموزشی و سرگرم‌کننده دارد و به دلیل کندی (O(n²))، هیچ کاربرد عملی در صنعت برای داده‌های بزرگ ندارد. با این حال، به خاطر سادگی فوق‌العاده‌اش (بدون حلقه‌های تو در تو)، گاهی در سیستم‌های بسیار کوچک یا میکروکنترلرها مورد توجه قرار می‌گیرد.