# ایده‌ی اصلی این الگوریتم، الهام‌گرفته‌شده از چیدن پنکیک‌ها با یک کفگیر است!
# فرض کنید یک پشته پنکیک با اندازه‌های مختلف دارید و فقط اجازه دارید کفگیر را از زیر یک پنکیک خاص ببرید و کل پشته‌ی بالای آن را یک‌جا برگردانید (برعکس کنید). هدف این است که پنکیک بزرگترین را ته پشته بگذارید، بعد دومین بزرگترین را، و الی آخر.
#
# در دنیای آرایه‌ها، تنها عملیات مجاز، «برگردان پیشوند» (Prefix Reversal) است؛ یعنی بخشی از ابتدای آرایه تا یک اندیس مشخص را کاملاً برعکس می‌کنیم.
#
# الگوریتم هر بار بزرگترین عنصر باقیمانده را پیدا می‌کند و با دو برگردان (Flip)، آن را به انتها می‌فرستد:
#
# بزرگترین عنصر را در بخش مرتب‌نشده پیدا کنید.
#
# برگردان اول: کل بخش از ابتدا تا جایی که آن عنصر بزرگ قرار دارد را برعکس کنید تا آن عنصر بزرگ به ابتدای آرایه بیاید.
#
# برگردان دوم: کل بخش مرتب‌نشده را (از ابتدا تا انتهای بخش مرتب‌نشده) برعکس کنید تا آن عنصر بزرگ به انتهای بخش مرتب‌نشده (درست قبل از عناصر قبلاً مرتب‌شده) برود.
#
# اندازه‌ی بخش مرتب‌نشده را یکی کم کنید و این کار را برای بقیه تکرار کنید.


# مرتبه‌ی زمانی (پیچیدگی): در بهترین، متوسط و بدترین حالت، همگی O(n²) هستند. (چون برای هر یک از n عنصر، باید دو بار آرایه را پیمایش کنیم: یک بار برای پیدا کردن بزرگترین عنصر، و یک بار برای برگردان‌ها).
#
# تعداد برگردان‌ها (Flips): حداکثر ۲n - ۳ بار برگردان انجام می‌دهد (یعنی در عمل خیلی کم‌تر از O(n²) جابه‌جایی دارد، اما خود برگردان‌ها O(n) زمان می‌برند).
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — کاملاً درجا (In-place) است و فقط با چند متغیر موقت کار می‌کند.
#
# آیا پایدار (Stable) است؟ خیر. عملیات برگرداندن (Reversal) ترتیب نسبی عناصر مساوی را به شدت به هم می‌ریزد.
#
# کاربرد اصلی: تقریباً به‌طور کامل آموزشی و تئوری است. این الگوریتم در درس‌های الگوریتم‌ها برای نشان دادن مفهوم «محدودیت عملیات» (مثلاً وقتی فقط اجازه‌ی برگردان داریم) استفاده می‌شود. همچنین در برخی مسائل خاص بیوانفورماتیک و ژنتیک (مثل مرتب‌سازی ژن‌ها) کاربردهای نظری دارد، اما در برنامه‌نویسی روزمره برای مرتب‌سازی داده‌ها، هرگز از آن استفاده نمی‌شود.
#
# مزیت خاص: اگر عملیات «برگرداندن بخشی از آرایه» در سخت‌افزار یا حافظه بسیار سریع و ارزان باشد (مثلاً با دستورات SIMD)، می‌تواند جالب توجه باشد، اما در عمل، الگوریتم‌های مدرن مانند IntroSort به‌مراتب برتر هستند.


