# طرز کار IntroSort
# ایده‌ی اصلی این الگوریتم، ترکیب هوشمندانه‌ی نقاط قوت سه الگوریتم دیگر است تا یک الگوریتم «همه‌کاره» بسازد که در هیچ شرایطی زمین نخورد. این سه الگوریتم عبارتند از:
#
# Quick Sort (برای سرعت بالا در حالت عادی)
#
# Heap Sort (برای تضمین سرعت در بدترین حالت)
#
# Insertion Sort (برای داده‌های کوچک)
#
# الگوریتم به این صورت کار می‌کند که با Quick Sort شروع می‌کند، اما مدام عمق بازگشت (Recursion Depth) را چک می‌کند. اگر عمق بازگشت از یک حد مجاز بیشتر شد، یعنی Quick Sort در حال افتادن به بدترین حالت (O(n²) است، پس بلافاصله تغییر استراتژی می‌دهد و بقیه‌ی کار را با Heap Sort انجام می‌دهد. همچنین برای تکه‌های بسیار کوچک آرایه، از Insertion Sort استفاده می‌کند.
#
# مراحل گام‌به‌گام:
#
# مرحله‌ی ۱: محاسبه‌ی حد مجاز عمق (Depth Limit)
# در ابتدای کار، یک عدد به عنوان حداکثر عمق بازگشت مجاز محاسبه می‌شود که معمولاً برابر است با:
# حداکثر عمق = ۲ × floor(log₂(n)) (که n تعداد عناصر آرایه است).
#
# مرحله‌ی ۲: شروع با Quick Sort (حالت عادی)
# الگوریتم مانند Quick Sort عمل می‌کند: یک محور (Pivot) انتخاب می‌کند، آرایه را حول آن بازچینی (Partition) می‌کند و سپس به‌صورت بازگشتی، دو زیرآرایه‌ی چپ و راست را مرتب می‌کند.
#
# مرحله‌ی ۳: بررسی عمق بازگشت (نقطه‌ی کلیدی)
# قبل از هر فراخوانی بازگشتی، عمق فعلی را با حد مجاز مقایسه می‌کند:
#
# اگر عمق فعلی < حد مجاز → ادامه می‌دهد با Quick Sort.
#
# اگر عمق فعلی == حد مجاز → فریاد می‌زند: «کافی است!» و بلافاصله Quick Sort را برای آن زیرآرایه متوقف می‌کند و همان زیرآرایه را با Heap Sort مرتب می‌کند. (چون Heap Sort در بدترین حالت هم O(n log n) است، پس سرعت تضمین می‌شود).
#
# مرحله‌ی ۴: استفاده از Insertion Sort برای زیرآرایه‌های کوچک
# حتی در مرحله‌ی Quick Sort، اگر اندازه‌ی یک زیرآرایه از یک آستانه (مثلاً ۱۶ عنصر) کمتر شد، الگوریتم دیگر Quick Sort را ادامه نمی‌دهد و مستقیماً از Insertion Sort برای آن تکه استفاده می‌کند. چون Insertion Sort روی آرایه‌های کوچک از هر الگوریتم دیگری سریع‌تر است.


# مرتبه‌ی زمانی (پیچیدگی):
#
# بهترین، متوسط و بدترین حالت: همگی O(n log n) هستند. (این بزرگترین دستاورد IntroSort است؛ برخلاف Quick Sort خالص که بدترین حالتش O(n²) است).
#
# مرتبه‌ی حافظه (فضای اضافی): O(log n) — چون در حالت عادی از Quick Sort پیروی می‌کند و درجا (In-place) عمل می‌کند و فقط به پشته‌ی بازگشت نیاز دارد. (برخلاف Merge Sort که O(n) حافظه می‌خواهد).
#
# آیا پایدار (Stable) است؟ خیر. چون از Quick Sort (که ناپایدار است) به عنوان هسته‌ی اصلی استفاده می‌کند.
#
# مزیت اصلی (چرا محبوب است؟):
#
# بهترین عملکرد عملی را در اکثر مواقع دارد (چون معمولاً مثل Quick Sort سریع است).
#
# امنیت دارد (چون در بدترین حالت ممکن، به Heap Sort پناه می‌برد و O(n²) نمی‌شود).
#
# حافظه‌ی کمی نسبت به Merge Sort مصرف می‌کند.
#
# از Insertion Sort برای داده‌های کوچک استفاده می‌کند که ضریب ثابت (Constant Factor) را به شدت پایین می‌آورد.
#
# کاربرد واقعی: الگوریتم مرتب‌سازی پیش‌فرض در بسیاری از پیاده‌سازی‌های مدرن زبان‌های برنامه‌نویسی است. برای مثال، الگوریتم std::sort در C++ (در اکثر کامپایلرها) دقیقاً از IntroSort استفاده می‌کند. همچنین در جاوا (Java) برای مرتب‌سازی انواع اولیه (Primitive types) از پیاده‌سازی مشابهی بهره می‌برند.
#
# معایب اصلی: پیاده‌سازی آن نسبت به الگوریتم‌های ساده پیچیده‌تر است و چون ناپایدار است، برای داده‌هایی که نیاز به حفظ ترتیب عناصر مساوی دارند، مناسب نیست (در آن موارد باید از Merge Sort استفاده کرد).
