def fib_dp(n):
    dp = [0]*(n+1)
    dp[0], dp[1] = 0, 1
    ops = 0
    for i in range(2, n+1):
        dp[i] = dp[i-1] + dp[i-2]
        ops += 1
    print("i: ", " ".join(map(str, range(n+1))))
    print("dp:", " ".join(map(str, dp)))
    print("operations:", ops)
    return dp

fib_dp(10)



from functools import lru_cache

@lru_cache(None)
def fib_memo(n):
    if n <= 1:
        return n
    return fib_memo(n-1) + fib_memo(n-2)

