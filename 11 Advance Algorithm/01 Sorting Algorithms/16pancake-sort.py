def flip(arr, i):
    arr[:i+1] = reversed(arr[:i+1])

def pancake_sort(arr):
    n = len(arr)
    for size in range(n, 1, -1):
        max_index = arr.index(max(arr[:size]))
        if max_index != size - 1:
            flip(arr, max_index)
            flip(arr, size - 1)
    return arr

print(pancake_sort([5, 3, 8, 4, 2]))




