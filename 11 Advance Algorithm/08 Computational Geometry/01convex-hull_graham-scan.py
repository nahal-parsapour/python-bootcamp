points = [(0,3),(1,1),(2,2),(4,4),
          (0,0),(1,2),(3,1),(3,3)]

def orientation(p, q, r):
    # cross product sign
    return (q[0]-p[0])*(r[1]-p[1]) - (q[1]-p[1])*(r[0]-p[0])

# کمترین y (اگر مساوی، کمترین x)
pivot = min(points, key=lambda p: (p[1], p[0]))

def polar_angle(p):
    import math
    return math.atan2(p[1]-pivot[1], p[0]-pivot[0])

sorted_pts = sorted(points, key=lambda p: (polar_angle(p), (p[0]-pivot[0])**2 + (p[1]-pivot[1])**2))

stack = []
for pt in sorted_pts:
    while len(stack) >= 2 and orientation(stack[-2], stack[-1], pt) <= 0:
        stack.pop()
    stack.append(pt)
    print("Stack:", stack)

print("Hull =", stack)



def all_collinear(points):
    if len(points) < 3:
        return True
    p0, p1 = points[0], points[1]
    for p in points[2:]:
        if orientation(p0, p1, p) != 0:
            return False
    return True

print("Collinear?", all_collinear(points))





# فرض کنید مجموعه‌ای از نقاط روی یک صفحه داریم. می‌خواهیم کوچک‌ترین چندضلعی محدب (Convex Hull) را رسم کنیم که همه‌ی نقاط را درون خود یا روی مرز خود جای دهد.
# مفهوم ساده‌تر: اگر به نقاط، میخ بکوبیم و یک کش دور همه‌ی آن‌ها بکشیم، شکلی که کش می‌گیرد، همان پوسته‌ی محدب است.
#
# طرز کار الگوریتم (اسکن گراهام)
# اسکن گراهام از یک پشته (Stack) و مرتب‌سازی بر اساس زاویه استفاده می‌کند. ایده این است که دور تا دور نقاط بچرخیم و همیشه مطمئن شویم که مسیر ما یک چرخش به چپ (Counter-Clockwise) دارد. اگر یک چرخش به راست (یا مستقیم) دیدیم، یعنی نقطه‌ی میانی اضافی است و باید آن را از پاسخ حذف کنیم.
#
# مراحل گام‌به‌گام:
#
# مرحله‌ی ۱: پیدا کردن نقطه‌ی شروع (پایین‌ترین و چپ‌ترین نقطه)
# تمام نقاط را بررسی کنید و نقطه‌ای را پیدا کنید که کمترین Y را دارد (پایین‌ترین نقطه). اگر بین چند نقطه، Y برابر بود، نقطه‌ای با کمترین X را انتخاب کنید. این نقطه را p0 (نقطه‌ی مبنا) می‌نامیم. مطمئن هستیم که این نقطه حتماً روی پوسته‌ی محدب قرار خواهد گرفت.
#
# مرحله‌ی ۲: مرتب‌سازی نقاط بر اساس زاویه‌ی قطبی
# بقیه‌ی نقاط را به ترتیب صعودی زاویه‌ای که با p0 و محور افقی می‌سازند مرتب کنید (در خلاف جهت عقربه‌های ساعت). اگر دو نقطه با p0 زاویه‌ی یکسانی داشته باشند (هم‌راستا)، فقط دورترین نقطه را نگه دارید و نزدیک‌تر را حذف کنید (برای ساده‌سازی و جلوگیری از خطا).
#
# مرحله‌ی ۳: پیمایش و ساخت پشته (هسته‌ی اصلی الگوریتم)
#
# سه نقطه‌ی اول (p0، نقطه‌ی اول و نقطه‌ی دوم از لیست مرتب‌شده) را داخل پشته قرار دهید.
#
# برای هر نقطه‌ی بعدی (p_new) در لیست مرتب، کار زیر را انجام دهید:
#
# تا زمانی که حداقل دو نقطه در پشته دارید و چرخش از دو نقطه‌ی بالای پشته به سمت نقطه‌ی جدید، یک چرخش به راست (یا مستقیم) باشد، نقطه‌ی بالای پشته را خارج (Pop) کنید.
#
# سپس p_new را به پشته اضافه (Push) کنید.
#
# ابزار ریاضی: تابع جهت‌یابی (Orientation)
# برای تشخیص چرخش به چپ یا راست، از ضرب خارجی (Cross Product) استفاده می‌کنیم:
# Orient(p, q, r) = (q.x - p.x) * (r.y - q.y) - (q.y - p.y) * (r.x - q.x)
#
# اگر مقدار > 0 باشد → چرخش به چپ (Counter-Clockwise) ← نقطه‌ی q خوب است و روی پوسته می‌ماند.
#
# اگر مقدار < 0 باشد → چرخش به راست (Clockwise) ← نقطه‌ی q باید از پشته خارج شود (چون برآمدگی به سمت داخل دارد).
#
# اگر مقدار == 0 باشد → نقاط هم‌راستا هستند ← معمولاً نقطه‌ی q را خارج می‌کنیم تا فقط دو رأس دورترین نقاط در پوسته بمانند.



# مرتبه‌ی زمانی (پیچیدگی): O(n log n) که n تعداد نقاط است. (مرتب‌سازی بر اساس زاویه O(n log n) زمان می‌برد و پیمایش با پشته O(n) زمان می‌برد، پس کل آن O(n log n) است).
#
# مرتبه‌ی حافظه (فضای اضافی): O(n) (برای نگهداری لیست مرتب‌شده و پشته).
#
# نحوه‌ی برخورد با نقاط هم‌راستا (Collinear): اگر سه نقطه روی یک خط مستقیم باشند، بسته به نیاز، یا دورترین‌ها را نگه می‌داریم و وسطی را حذف می‌کنیم، یا همه را نگه می‌داریم. در این الگوریتم معمولاً برای سادگی، نقاط میانی را حذف می‌کنیم.
#
# پیش‌نیاز هندسی: باید با مفهوم ضرب خارجی (Cross Product) و محاسبه‌ی زاویه‌ی قطبی آشنا باشید.
#
# مزیت اصلی: ساده‌ترین و سریع‌ترین الگوریتم برای محاسبه‌ی پوسته‌ی محدب برای داده‌های عمومی است. پیاده‌سازی آن بسیار سرراست است و به‌خوبی روی مجموعه‌های با هر اندازه‌ای کار می‌کند.
#
# مقایسه با الگوریتم‌های مشابه:
#
# در مقایسه با الگوریتم مونوتون زنجیره‌ای (Andrew's Monotone Chain)، گراهام اسکن نیاز به محاسبه‌ی زاویه دارد (که شامل تقسیم و توابع مثلثاتی گران‌قیمت است، هرچند با استفاده از مقایسه‌ی atan2 یا خود تابع Orientation قابل حل است). مونوتون چین از مرتب‌سازی بر اساس X و Y استفاده می‌کند و سریع‌تر است، اما گراهام اسکن از نظر مفهومی زیباتر و کلاسیک‌تر محسوب می‌شود.
