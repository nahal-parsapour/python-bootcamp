# طرز کار Bitonic Sort
# ایده‌ی اصلی این الگوریتم، بر پایه‌ی یک مفهوم ریاضی به نام «دنباله‌ی بایتونیک» (Bitonic Sequence) استوار است.
# یک دنباله‌ی بایتونیک، دنباله‌ای است که ابتدا به‌صورت صعودی (اکیداً یا نااکیداً) مرتب می‌شود و سپس به‌صورت نزولی مرتب می‌شود.
# به عبارت دیگر، دنباله‌ای که فقط یک قله (Peak) دارد، مثل: [1, 3, 5, 9, 7, 4, 2] (ابتدا بالا می‌رود و بعد پایین می‌آید).
#
# بایتونیک سورت از این ویژگی به‌طرز هوشمندانه‌ای استفاده می‌کند و یک شبکه‌ی مرتب‌سازی (Sorting Network) موازی است. الگوریتم به‌صورت بازگشتی کار می‌کند و دو فاز اصلی دارد:
#
# فاز اول: ساخت دنباله‌ی بایتونیک (Bitonic Formation)
# آرایه را به دو نیمه تقسیم می‌کند. نیمه‌ی اول را به‌صورت صعودی مرتب می‌کند و نیمه‌ی دوم را به‌صورت نزولی مرتب می‌کند. با چسباندن این دو نیمه به هم، یک دنباله‌ی بایتونیک کامل به دست می‌آید (چون اول صعودی است و بعد نزولی).
#
# فاز دوم: ادغام بایتونیک (Bitonic Merge)
# این فاز، قلب الگوریتم است. یک دنباله‌ی بایتونیک را گرفته و آن را به یک دنباله‌ی کاملاً مرتب (صعودی) تبدیل می‌کند. برای این کار:
#
# عناصر نیمه‌ی اول را با عناصر متناظر در نیمه‌ی دوم (با فاصله‌ی n/2) مقایسه می‌کند و اگر اولی بزرگ‌تر از دومی بود، آن‌ها را جابه‌جا می‌کند.
#
# پس از این مقایسه‌ها، دنباله به دو نیمه‌ی بایتونیک کوچک‌تر تقسیم می‌شود (همه‌ی عناصر کوچک‌تر در نیمه‌ی اول و همه‌ی بزرگ‌ترها در نیمه‌ی دوم قرار می‌گیرند).
#
# سپس همین فرایند ادغام را به‌صورت بازگشتی روی هر دو نیمه اجرا می‌کند تا در نهایت کل آرایه مرتب شود.



# مرتبه‌ی زمانی (پیچیدگی):
#
# در اجرای ترتیبی (تک‌هسته‌ای) : O(n log² n) — که از Merge Sort و Quick Sort کندتر است.
#
# در اجرای موازی (Parallel) : O(log² n) — این عدد شگفت‌انگیزی است! به همین دلیل برای پردازنده‌های چند هسته‌ای و پردازنده‌های گرافیکی (GPU) ایده‌آل است.
#
# مرتبه‌ی حافظه (فضای اضافی): در پیاده‌سازی نرم‌افزاری معمولاً O(n) است، اما در سخت‌افزار (به‌عنوان شبکه‌ی مرتب‌سازی) نیاز به O(n log² n) مقایسه‌گر دارد.
#
# آیا پایدار (Stable) است؟ خیر. چون جابه‌جایی‌های گسترده بین عناصر با فاصله‌های دور انجام می‌شود.
#
# محدودیت اصلی: تعداد عناصر آرایه باید دقیقاً توانی از ۲ (۲، ۴، ۸، ۱۶، ...) باشد. اگر تعداد عناصر توان دو نباشد، باید آرایه را با اعداد بی‌نهایت (بزرگ‌ترین مقدار ممکن) پد کنید (پر کردن) و بعد از مرتب‌سازی، آن‌ها را حذف کنید.
#
# مزیت اصلی (چرا استفاده می‌شود؟): اگر پردازنده‌ی چند هسته‌ای در اختیار داشته باشید، این الگوریتم به طرز باورنکردنی سریع است. به همین دلیل در برنامه‌نویسی CUDA (کارت‌های گرافیکی انویدیا) و سیستم‌های FPGA (مدارهای قابل برنامه‌ریزی) برای مرتب‌سازی حجم عظیم داده به‌کار می‌رود. همچنین به خاطر ساختار منظم و قابل پیش‌بینی‌اش، در سخت‌افزار به‌راحتی پیاده‌سازی می‌شود.