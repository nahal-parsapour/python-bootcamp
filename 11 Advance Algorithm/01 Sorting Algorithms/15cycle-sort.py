def cycle_sort(arr):
    writes = 0

    for cycle_start in range(len(arr)):
        item = arr[cycle_start]

        pos = cycle_start
        for i in range(cycle_start + 1, len(arr)):
            if arr[i] < item:
                pos += 1

        if pos == cycle_start:
            continue

        while item == arr[pos]:
            pos += 1

        arr[pos], item = item, arr[pos]
        writes += 1

        while pos != cycle_start:
            pos = cycle_start
            for i in range(cycle_start + 1, len(arr)):
                if arr[i] < item:
                    pos += 1

            while item == arr[pos]:
                pos += 1
            arr[pos], item = item, arr[pos]
            writes += 1

    return arr, writes

print(cycle_sort([5, 3, 8, 4, 2]))



# طرز کار Cycle Sort
# ایده‌ی اصلی این الگوریتم، کمینه‌سازی تعداد دفعات نوشتن (Writes) روی حافظه است. به جای اینکه عناصر را یکی‌یکی و بی‌هدف جابه‌جا کند، سعی می‌کند هر عنصر را مستقیماً و تنها یک بار در جای نهایی‌اش قرار دهد.
#
# این کار با استفاده از مفهوم ریاضی «چرخه‌های جایگشت» (Permutation Cycles) انجام می‌شود. اگر آرایه را به عنوان یک جایگشت در نظر بگیریم، عناصر آن در یک سری چرخه قرار می‌گیرند. الگوریتم هر چرخه را پیدا کرده و با چرخاندن عناصر درون آن، همه را به جای درستشان می‌فرستد.
#
# مراحل گام‌به‌گام:
#
# از ابتدای آرایه (اندیس i = 0) شروع می‌کنیم تا به انتها برویم.
#
# عنصر جاری را در متغیر item ذخیره می‌کنیم.
#
# محاسبه‌ی جایگاه درست (محاسبه‌ی pos): تعداد عناصری که از item کوچک‌تر هستند را در کل آرایه شمارش می‌کنیم. (اگر عناصر تکراری داریم، برای پایداری در جابه‌جایی، عناصر مساوی را نادیده می‌گیریم تا چرخه به هم نخورد). این عدد، دقیقاً اندیسی است که item باید در آرایه‌ی مرتب‌شده در آن قرار بگیرد.
#
# اگر pos برابر با اندیس فعلی (i) بود، یعنی عنصر در جای خودش است. پس آن را نادیده گرفته و به سراغ عنصر بعدی می‌رویم.
#
# اگر pos با i برابر نبود، یعنی عنصر باید جابه‌جا شود. چرخه را شروع می‌کنیم:
#
# عنصر جاری (item) را با عنصری که در اندیس pos قرار دارد، جابه‌جا می‌کنیم. (حالا item در جای نهایی خودش نشسته است و عنصر قبلیِ pos تبدیل به item جدید شده است).
#
# دوباره برای item جدید، جایگاه درستش (pos) را با شمارش عناصر کوچک‌تر از آن محاسبه می‌کنیم.
#
# این جابه‌جایی را تکرار می‌کنیم تا وقتی که pos دوباره برابر با اندیس شروع چرخه (همان i) شود. یعنی چرخه کامل شده است.
#
# مرحله‌ی ۲ تا ۵ را برای تمام اندیس‌های آرایه تکرار می‌کنیم.



# مرتبه‌ی زمانی (پیچیدگی): O(n²) در بهترین، متوسط و بدترین حالت. (چون برای هر عنصر، باید کل آرایه را بگردیم تا تعداد عناصر کوچک‌تر را بشماریم، در حالی که مرتب‌سازی اصلی در O(n) انجام می‌شود. پس بخش شمارش، گلوگاه است).
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — کاملاً درجا (In-place) است و هیچ حافظه‌ی اضافی مصرف نمی‌کند.
#
# تعداد نوشتن‌ها (Writes) روی حافظه: این نقطه‌ی قوت اصلی آن است. تعداد نوشتن‌ها در بدترین حالت، حداکثر ۳n است که از همه‌ی الگوریتم‌های دیگر کمتر است. (برای مقایسه، Selection Sort تا n نوشتن دارد، اما Cycle Sort حتی از آن هم در عمل بهینه‌تر است، چون هر چرخه را با یک حرکت می‌چرخاند).
#
# آیا پایدار (Stable) است؟ خیر. چون عناصر با فواصل دور جابه‌جا می‌شوند، ترتیب عناصر مساوی به هم می‌ریزد. (اگر به دنبال پیاده‌سازی پایدار باشید، باید هنگام شمارش عناصر کوچک‌تر، از <= استفاده کنید که باعث می‌شود چرخه‌ها شکل دیگری بگیرند، اما معمولاً ناپایدار در نظر گرفته می‌شود).
#
# چه زمانی از آن استفاده می‌کنیم؟ وقتی که عملیات نوشتن (Write) روی حافظه بسیار گران‌قیمت است. مثلاً در حافظه‌های EEPROM، فلش مموری (Flash Memory) یا دیسک‌های مکانیکی که تعداد دفعات نوشتن، طول عمر دستگاه را کاهش می‌دهد. در چنین مواردی، حتی اگر الگوریتم کند باشد (O(n²)، چون تعداد مقایسه‌ها زیاد است اما تعداد نوشتن‌ها بسیار کم است، انتخاب ایده‌آلی محسوب می‌شود.
#
# معایب اصلی: بسیار کند است (O(n²)، مخصوصاً برای آرایه‌های بزرگ که مقایسه‌ها زیاد می‌شود) و پیاده‌سازی آن نسبت به Bubble Sort یا Insertion Sort کمی پیچیده‌تر است. برای کاربردهای عمومی که سرعت اهمیت دارد، هرگز از آن استفاده نمی‌شود.