# Comparison-Based Sorting Algorithms

def bubble_sort(arr):
    n = len(arr)
    comparisons = 0
    swaps = 0

    for i in range(n):
        swapped = False
        for j in range(0, n - i - 1):
            comparisons += 1
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swaps += 1
                swapped = True
        if not swapped:
            break

    return arr, comparisons, swaps

print(bubble_sort([5, 3, 8, 0, 4, 2]))





# طرز کار Bubble Sort
# ایده‌ی اصلی این الگوریتم بسیار شهودی است:
# عناصر سنگین‌تر (بزرگ‌تر) مانند حباب در آب، به سمت انتهای لیست شناور می‌شوند.
#
# الگوریتم با مقایسه‌ی دو عنصر مجاور کار می‌کند و اگر ترتیب آن‌ها اشتباه باشد، آن‌ها را جابه‌جا (Swap) می‌کند.
# با هر پاس کامل، بزرگترین عنصر باقیمانده در انتهای لیست قرار می‌گیرد.
#
# مراحل گام‌به‌گام:
#
# از اولین عنصر آرایه شروع کنید.
#
# عنصر جاری را با عنصر بعد از خودش مقایسه کنید.
#
# اگر عنصر جاری بزرگ‌تر از عنصر بعدی بود، آن دو را جابه‌جا کنید (تا عنصر بزرگتر به سمت راست برود).
#
# یک قدم به جلو بروید و این مقایسه را برای جفت‌های بعدی انجام دهید تا به انتهای آرایه برسید.
#
# پس از پایان این یک پاس، بزرگترین عنصر در آخرین خانه‌ی آرایه قرار گرفته است (پس دیگر نیازی به بررسی آن نداریم).
#
# مراحل ۱ تا ۴ را دوباره برای آرایه تکرار کنید، اما این بار فقط تا یک خانه قبل از آخر (چون آخرین خانه قبلاً در جای خودش است).
#
# این کار را آنقدر ادامه دهید تا در یک پاس کامل، هیچ جابه‌جایی انجام نشود (یعنی آرایه مرتب شده است).




# مرتبه‌ی زمانی (پیچیدگی): حالت متوسط و بدترین: O(n²) (چون باید دو حلقه‌ی تو‌درتو اجرا شود).
#
# بهترین حالت (آرایه از قبل مرتب): اگر بهینه‌سازی «پرچم جابه‌جایی» را اضافه کنید، فقط یک پاس انجام می‌دهد و متوقف می‌شود، پس O(n) می‌شود.
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) چون همه‌ی کارها را درون خود آرایه (In-place) و فقط با یک متغیر موقت برای جابه‌جایی انجام می‌دهد.
#
# آیا پایدار (Stable) است؟ بله. اگر دو عدد مساوی داشته باشیم، آن‌ها را جابه‌جا نمی‌کند (چون شرط فقط برای بزرگ‌تر است)، پس ترتیب نسبی عناصر مساوی حفظ می‌شود.
#
# مزیت و معایب: فهمیدن و پیاده‌سازی آن بسیار ساده است، اما به دلیل سرعت پایین (O(n²)، تقریباً هرگز برای داده‌های حجیم استفاده نمی‌شود و بیشتر جنبه‌ی آموزشی دارد.