# Non-Comparison Sorting Algorithms

def counting_sort(arr):
    mx = max(arr)
    count = [0]*(mx+1)

    for num in arr:
        count[num] += 1

    result = []
    for i in range(len(count)):
        result.extend([i]*count[i])

    return result

print(counting_sort([5, 3, 8, 0, 4, 4, 2]))



