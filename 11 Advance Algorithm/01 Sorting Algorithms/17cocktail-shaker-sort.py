# ایده‌ی اصلی این الگوریتم، بهبود نسخه‌ی ساده‌ی مرتب‌سازی حبابی (Bubble Sort) است.
# در Bubble Sort معمولی، ما همیشه از چپ به راست حرکت می‌کنیم و بزرگترین عنصر را در هر پاس به انتها می‌فرستیم. اما مشکل اینجاست که عناصر کوچک در انتهای آرایه، هر بار فقط یک خانه به سمت چپ حرکت می‌کنند و این باعث کندی می‌شود.
#
# مرتب‌سازی کوکتل شیکر این مشکل را با حرکت در هر دو جهت حل می‌کند:
#
# در یک پاس، از چپ به راست می‌رویم (مثل Bubble Sort) و بزرگترین عنصر را به انتها می‌فرستیم.
#
# در پاس بعدی، از راست به چپ برمی‌گردیم و کوچکترین عنصر را به ابتدا می‌فرستیم.
#
# این رفت و برگشت (مثل حرکت یک شیکر!) را آنقدر تکرار می‌کنیم تا هیچ جابه‌جایی در یک رفت و برگشت کامل رخ ندهد.
#
# مراحل گام‌به‌گام:
#
# دو مرز برای بخش مرتب‌نشده تعیین می‌کنیم: start = 0 (ابتدای آرایه) و end = n-1 (انتهای آرایه).
#
# فاز رفت (چپ به راست): از start تا end پیمایش می‌کنیم. هر جفت مجاور که ترتیبشان اشتباه بود را جابه‌جا می‌کنیم. در پایان این فاز، بزرگترین عنصر در اندیس end قرار می‌گیرد. سپس end را یکی کم می‌کنیم (چون آخرین خانه مرتب شده است).
#
# فاز برگشت (راست به چپ): از end تا start به عقب پیمایش می‌کنیم. هر جفت مجاور که ترتیبشان اشتباه بود را جابه‌جا می‌کنیم. در پایان این فاز، کوچکترین عنصر در اندیس start قرار می‌گیرد. سپس start را یکی زیاد می‌کنیم (چون اولین خانه مرتب شده است).
#
# مراحل ۲ و ۳ را تکرار می‌کنیم تا زمانی که start از end بزرگتر شود یا در یک دور کامل رفت و برگشت، هیچ جابه‌جایی رخ ندهد.




# مرتبه‌ی زمانی (پیچیدگی):
#
# بهترین حالت (آرایه از قبل مرتب): O(n) — زیرا با یک بار رفت و برگشت متوجه می‌شود که هیچ جابه‌جایی رخ نداده و متوقف می‌شود.
#
# حالت متوسط و بدترین حالت: O(n²) — مانند Bubble Sort.
#
# مرتبه‌ی حافظه (فضای اضافی): O(1) — کاملاً درجا (In-place) است و فقط با یک متغیر موقت جابه‌جایی انجام می‌دهد.
#
# آیا پایدار (Stable) است؟ بله. شرط جابه‌جایی فقط برای «بزرگ‌تر» است، پس عناصر مساوی جابه‌جا نمی‌شوند و ترتیب نسبی آن‌ها حفظ می‌گردد.
#
# مزیت نسبت به Bubble Sort معمولی: در Bubble Sort، عناصر کوچک انتهای آرایه با سرعت یک خانه در هر پاس به ابتدا حرکت می‌کنند. اما در کوکتل شیکر، این عناصر در فاز برگشت، با سرعت بیشتری به ابتدا می‌رسند. بنابراین برای آرایه‌هایی که عناصر کوچک در انتها دارند، حدوداً ۲ برابر سریع‌تر از Bubble Sort عمل می‌کند.
#
# معایب اصلی: هنوز هم یک الگوریتم O(n²) است و برای داده‌های بزرگ اصلاً مناسب نیست. پیاده‌سازی آن کمی پیچیده‌تر از Bubble Sort ساده است و کاربرد اصلی آن بیشتر جنبه‌ی آموزشی دارد تا عملی.
