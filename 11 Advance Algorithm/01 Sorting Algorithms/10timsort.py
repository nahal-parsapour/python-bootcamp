# طرز کار Timsort
# تیم‌سورت یک الگوریتم ترکیبی (Hybrid) است که از دو الگوریتم مرتب‌سازی درجی (Insertion Sort) و مرتب‌سازی ادغامی (Merge Sort) الهام گرفته است. این الگوریتم به‌عنوان الگوریتم پیش‌فرض مرتب‌سازی در زبان‌های پایتون (از نسخه ۲.۳ به بعد)، جاوا (برای مرتب‌سازی اشیاء) و اندروید استفاده می‌شود.
#
# ایده‌ی اصلی و هوشمندانه‌ی تیم‌سورت این است که داده‌های دنیای واقعی معمولاً تا حدی مرتب هستند. به جای نادیده گرفتن این موضوع، تیم‌سورت از این نظم طبیعی (که به آن «اجرا» (Run) می‌گویند) نهایت بهره را می‌برد و آن‌ها را به هم می‌چسباند.
#
# مراحل گام‌به‌گام:
#
# مرحله‌ی ۱: تشخیص اجراهای طبیعی (Identify Natural Runs)
# الگوریتم از ابتدای آرایه شروع می‌کند و به دنبال زیرآرایه‌هایی می‌گردد که از قبل مرتب هستند. این زیرآرایه‌ها را «اجرا» (Run) می‌نامیم.
#
# اگر آرایه صعودی است ([2, 5, 7, ...])، همان را به عنوان یک اجرا در نظر می‌گیرد.
#
# اگر آرایه نزولی است ([9, 7, 4, ...])، آن را برعکس (معکوس) می‌کند تا یک اجرای صعودی شود (چون معکوس کردن نزولی، همان صعودی می‌شود).
#
# مرحله‌ی ۲: حداقل طول اجرا (Minrun)
# تیم‌سورت یک عدد جادویی به نام Minrun محاسبه می‌کند (معمولاً بین ۳۲ تا ۶۴). اگر یک اجرای طبیعی پیدا شده از Minrun کوچک‌تر باشد، الگوریتم از مرتب‌سازی درجی (Insertion Sort) برای ادامه دادن و بزرگ‌تر کردن آن اجرا تا رسیدن به طول Minrun استفاده می‌کند. (چون Insertion Sort روی داده‌های کوچک فوق‌العاده سریع است).
#
# مرحله‌ی ۳: ذخیره‌سازی اجراها در پشته (Stack)
# طول و نقطه‌ی شروع هر اجرا را در یک پشته ذخیره می‌کند. اما نمی‌گذارد اجراها هرجوری در پشته انباشته شوند. یک قانون سخت‌گیرانه دارد:
# طول هر سه اجرای بالای پشته باید شرط A > B + C و B > C را برقرار کند (برای متعادل نگه داشتن اندازه‌ها). اگر این شرط نقض شود، الگوریتم دو اجرای بالایی را که کوچک‌تر هستند با هم ادغام (Merge) می‌کند تا تعادل برقرار شود.
#
# مرحله‌ی ۴: ادغام هوشمند (Merging with Galloping)
# وقتی نوبت به ادغام دو اجرا می‌رسد، تیم‌سورت از یک تکنیک فوق‌العاده به نام «تاختن (Galloping Mode) استفاده می‌کند:
#
# ابتدا دو اجرا را با هم مقایسه می‌کند. اگر یکی از اجراها مرتباً از دیگری کوچک‌تر باشد (مثلاً همه‌ی عناصر اجرای چپ، از عناصر ابتدایی اجرای راست کوچک‌تر هستند)، الگوریتم به جای یکی‌یکی مقایسه کردن، با جهش‌های تصاعدی (1, 2, 4, 8, ...) حرکت می‌کند تا یکجا کل آن بخش را انتقال دهد. این کار باعث کاهش چشمگیر تعداد مقایسه‌ها می‌شود.



# مرتبه‌ی زمانی (پیچیدگی):
# 
# بهترین حالت (آرایه از قبل مرتب): O(n) — الگوریتم فقط یک بار اجراها را تشخیص می‌دهد و بدون ادغام‌های سنگین، کار تمام می‌شود!
#
# حالت متوسط و بدترین حالت: O(n log n) — مثل Merge Sort، عملکرد تضمینی دارد.
#
# مرتبه‌ی حافظه (فضای اضافی): O(n) — برای عملیات ادغام به حافظه‌ی کمکی نیاز دارد (مشابه Merge Sort).
#
# آیا پایدار (Stable) است؟ بله. هم Insertion Sort و هم Merge Sort به‌صورت پایدار پیاده‌سازی می‌شوند، بنابراین ترتیب عناصر مساوی حفظ می‌گردد.
#
# مزیت اصلی (چرا بهترین الگوریتم عملی است؟):
#
# از نظم طبیعی داده‌ها استفاده می‌کند (خیلی سریع‌تر از سایر الگوریتم‌ها در داده‌های نیمه‌مرتب).
#
# با تکنیک Galloping، تعداد مقایسه‌ها را در ادغام به شدت کاهش می‌دهد.
#
# عملکرد تضمینی O(n log n) در بدترین حالت دارد (برخلاف Quick Sort که ممکن است به O(n²) برسد).
#
# برای داده‌های کوچک از Insertion Sort استفاده می‌کند که سریع‌ترین گزینه است.
#
# معایب اصلی: پیاده‌سازی آن بسیار پیچیده‌تر از الگوریتم‌های ساده است و نیاز به درک عمیقی از بهینه‌سازی‌های سطح پایین دارد. همچنین مانند Merge Sort، حافظه‌ی اضافی مصرف می‌کند.