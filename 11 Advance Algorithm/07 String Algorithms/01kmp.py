pattern = "ABABCABAB"
n = len(pattern)
lps = [0]*n

length = 0  # طول قبلی longest prefix-suffix
i = 1

while i < n:
    if pattern[i] == pattern[length]:
        length += 1
        lps[i] = length
        i += 1
    else:
        if length != 0:
            length = lps[length-1]
        else:
            lps[i] = 0
            i += 1

print("Index:  ", " ".join(map(str, range(n))))
print("Pattern:", " ".join(pattern))
print("LPS:    ", " ".join(map(str, lps)))




