arr = list(range(2, 20000, 2))
target = 642

bound = 1
print("bound =", bound)

while bound < len(arr) and arr[bound] < target:
    bound *= 2
    print("bound =", bound)

low = bound // 2
high = min(bound, len(arr)-1)

print("Range found:", low, high)



path = []
while low <= high:
    mid = (low + high) // 2
    path.append(arr[mid])

    if arr[mid] == target:
        break
    elif arr[mid] < target:
        low = mid + 1
    else:
        high = mid - 1

print("path:", path)




# طرز کار Exponential Search
# ایده‌ی اصلی این الگوریتم، پیدا کردن یک بازه‌ی کوچک که هدف در آن قرار دارد، با استفاده از پرش‌های نمایی (۱، ۲، ۴، ۸، ۱۶، ...) است. به محض اینکه بازه‌ی مورد نظر پیدا شد، یک جستجوی دودویی (Binary Search) استاندارد روی همان بازه انجام می‌دهیم تا هدف را بیابیم.
#
# این الگوریتم زمانی بسیار عالی عمل می‌کند که هدف به ابتدای آرایه نزدیک باشد، یا زمانی که اندازه‌ی آرایه را نمی‌دانیم (مثلاً در جریان داده‌های بی‌نهایت یا فایل‌های بسیار بزرگ با انتهای نامعلوم).
#
# مراحل گام‌به‌گام (برای آرایه‌ی صعودی):
#
# اگر اولین عنصر آرایه (arr[0]) برابر با هدف بود، اندیس 0 را برگردانید (حالت خاص).
#
# یک متغیر index = 1 در نظر بگیرید.
#
# تا زمانی که index از طول آرایه کمتر است و arr[index] < target، مرحله‌ی ۴ را تکرار کنید:
#
# index را دو برابر کنید: index = index * 2.
#
# حالا یا به انتهای آرایه رسیده‌اید، یا به عنصری رسیده‌اید که از هدف بزرگ‌تر یا مساوی است.
# بازه‌ی جستجو را مشخص کنید:
#
# شروع بازه: low = index / 2 (همان اندیس قبلی که مطمئن هستید از هدف کوچک‌تر است).
#
# پایان بازه: high = min(index, n-1) (یا همان اندیس فعلی، یا انتهای آرایه).
#
# یک جستجوی دودویی (Binary Search) استاندارد روی بازه‌ی [low, high] اجرا کنید.
#
# اگر جستجوی دودویی هدف را پیدا کرد، اندیس آن را برگردانید؛ در غیر این صورت، یعنی هدف در آرایه وجود ندارد و مقدار -1 را برگردانید.



# مرتبه‌ی زمانی (پیچیدگی):
#
# اگر هدف در اندیس i قرار داشته باشد، فاز پرش‌های نمایی O(log i) زمان می‌برد و فاز جستجوی دودویی نیز O(log i) زمان می‌برد، بنابراین مجموعاً O(log i).
#
# در بدترین حالت (هدف در انتهای آرایه یا وجود نداشته باشد)، i = n است، پس پیچیدگی کل به O(log n) می‌رسد (دقیقاً برابر با جستجوی دودویی).
#
# مرتبه‌ی حافظه (فضای اضافی):
#
# پیاده‌سازی تکراری (Iterative): O(1) — هیچ حافظه‌ی اضافی مصرف نمی‌کند.
#
# پیاده‌سازی بازگشتی (برای بخش جستجوی دودویی): O(log n) برای پشته‌ی فراخوانی.
#
# پیش‌نیاز اصلی: آرایه باید مرتب (Sorted) باشد.
#
# بهترین حالت: اگر هدف در ابتدای آرایه باشد (مثلاً اندیس ۱ یا ۲)، الگوریتم فقط چند پرش کوچک انجام می‌دهد و خیلی زود به جستجوی دودویی می‌رسد. در این حالت، از جستجوی دودویی استاندارد (که همیشه از وسط شروع می‌کند) بسیار سریع‌تر است.
#
# کاربرد ویژه (مهم): این الگوریتم برای آرایه‌های با اندازه‌ی نامعلوم (Unbounded Arrays) یا جریان‌های داده (Data Streams) که انتهای آن‌ها مشخص نیست، ایده‌آل است. چون جستجوی دودویی برای شروع نیاز به دانستن high دارد، اما Exponential Search با دوبرابر کردن اندیس، خودش انتهای بازه را کشف می‌کند.
#
# معایب اصلی: اگر هدف به انتهای آرایه نزدیک باشد، تعداد پرش‌های نمایی زیاد می‌شود (حدود log n پرش) و سپس یک جستجوی دودویی دیگر انجام می‌دهد. در این حالت، عملاً دو برابر جستجوی دودویی خالص زمان می‌برد (چون جستجوی دودویی مستقیم از همان ابتدا شروع می‌کرد). بنابراین برای آرایه‌هایی که اندازه‌ی آن‌ها مشخص است و هدف به طور تصادفی توزیع شده، Binary Search انتخاب بهتر و ساده‌تری است.