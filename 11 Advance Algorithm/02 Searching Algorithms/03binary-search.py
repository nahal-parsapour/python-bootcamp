arr = [3, 8, 12, 17, 25, 31, 39, 44, 58]
target = 31

low, high = 0, len(arr) - 1

while low <= high:
    mid = (low + high) // 2
    print(f"low={low}, mid={mid}, high={high}, arr[mid]={arr[mid]}")

    if arr[mid] == target:
        print("Founded!")
        break
    elif arr[mid] < target:
        low = mid + 1
    else:
        high = mid - 1


def binary_search_path(arr, target):
    low, high = 0, len(arr) - 1
    path = []

    while low <= high:
        mid = (low + high) // 2
        path.append(arr[mid])

        if arr[mid] == target:
            return path
        elif arr[mid] < target:
            low = mid + 1
        else:
            high = mid - 1

    return path

print(binary_search_path(arr, target))



